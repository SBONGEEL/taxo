/** سطرُ شهادةٍ يكتبه الحارسُ بنفسه — **موقَّتاً وبأرقامه**.
 *
 * **القاعدةُ التي أنشأته** (قرارُ المالك 2026-08-23، الشكلُ الخامسَ عشر):
 * حارسٌ يُشغَّل ولا يُسجَّل رقمُه **يُنسخ نصُّه بعد أسبوع بلا تشغيل**، ولا شيءَ
 * يفرّق النسختين. أما «✓ check:sheet · ٣ أوراق · 2026-08-23T08:12Z» فهو
 * **دعوى قابلةٌ للتكذيب**: من قرأها يستطيع أن يُشغّل ويقارن.
 *
 * **و`HANDOFF.md` يلصق ولا يصوغ**: ما لا يحمل سطراً كهذا **يُقرأ «لم
 * يُشغَّل»** — لا فراغاً. وهو الفرقُ بين «مرّ» و«ما الذي قِيس ليقول مرّ؟».
 *
 * **ولا يُبنى على نجاحٍ مفترَض**: يُنادى في مسار النجاح وحدَه، بعد أن يكون
 * الحارسُ قد قرّر. فسطرُه **أثرُ قياسٍ وقع**، لا إعلانُ نيّة.
 */

/** الوقتُ بدقّة الدقيقة — الثواني ضجيجٌ في سطرٍ يُقرأ بالعين. */
function stamp() {
  return new Date().toISOString().slice(0, 16) + "Z";
}

/** يطبع سطرَ الشهادة. `name` اسمُ الحارس كما يُنادى، و`facts` أرقامُه. */
export function certify(name, ...facts) {
  const clean = (part) =>
    String(part)
      // **تُنزع «✓» الداخلية**: الحرّاسُ كتبوا رسائلَهم قبل هذا السطر،
      // فبقاؤها يُنتج «✓ … · ✓ …»
      .replace(/^\s*✓\s*/, "")
      // **ويُطوى السطرُ الواحد**: رسالةٌ على أسطرٍ تكسر شهادةً تُقرأ سطراً
      .replace(/\s+/g, " ")
      .trim();
  const parts = facts
    .filter((part) => part !== undefined && part !== null && clean(part) !== "")
    .map(clean);
  console.log(`✓ ${name} · ${parts.join(" · ")} · ${stamp()}`);
}
