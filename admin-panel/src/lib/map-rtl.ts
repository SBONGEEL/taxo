/** **تشكيلُ العربية على الخريطة — يُستورَد قبل أن تُنشأ أيُّ خريطة.**
 *
 * `mapbox-gl` يرسم النصَّ في لوحةٍ (canvas) لا في DOM، فلا يملك مُشكِّلَ
 * المتصفّح: يأخذ الحروفَ **بترتيب الكتابة** ويضع لكلِّ حرفٍ صورتَه المعزولة
 * من اليسار إلى اليمين. فتُقرأ «منطقة زهران» **«نارهز ةقطنم»** — منفصلةً
 * ومعكوسة. **والعطبُ في اللوحة وحدَها**: نصُّ التطبيق حولها سليمٌ لأن
 * المتصفّح هو الذي يرسمه، وهو ما يجعل العطبَ يبدو انتقائياً وليس كذلك.
 *
 * وعلاجُه ملحقٌ واحد — `@mapbox/mapbox-gl-rtl-text` — يُحمَّل داخل عامل
 * الخريطة فيطبّق تشكيلَ العربية وخوارزميةَ الاتجاهين.
 *
 * **وثلاثةُ قيودٍ تجعل هذا الملفَّ بيتَه الوحيد:**
 *
 * ١. **`setRTLTextPlugin` عامٌّ على الوحدة لا على الخريطة**، **ويرمي إن نُودي
 *    مرّتين**. وفي كلِّ تطبيقٍ أكثرُ من خريطةٍ (الشاشةُ ومعاينةُ الكسوة)، فلو
 *    ناداه كلُّ مكوِّنٍ لسقط الثاني. فالنداءُ هنا مرّةً واحدةً عند تقييم
 *    الوحدة، **وحالتُه تُسأل قبله** فلا يضرّه استيرادٌ متكرّر.
 *
 * ٢. **ويُنادى قبل `new mapboxgl.Map` لا بعده.** الاستيرادُ في رأس الملفّ
 *    يضمن ذلك: وحداتُ ES تُقيَّم قبل جسم المستورِد.
 *
 * ٣. **والملفُّ يُخدَم من أصلنا لا من CDN** — من `public/vendor/`. فالتطبيقاتُ
 *    تعمل في غلافٍ يشير إلى نطاقنا، **وملحقٌ من شبكةٍ ثالثةٍ يجعل تعريبَ
 *    الخريطة رهينةَ مضيفٍ لا نملكه.**
 *
 *    **ولا يُستورَد من الحزمة**: `exports` فيها **سلسلةٌ واحدة** تكشف
 *    `./src/index.js` وحدَه، فاستيرادُ `dist/…?url` **يمرّ في خادم التطوير
 *    ويسقط في البناء** — وقع مقيساً. والنسخةُ يزامنها `check:rtl` مع كلِّ
 *    بناءٍ فلا تتخلّف عن حزمتها صامتةً.
 *
 * **ولا يغيّر هذا لغةَ الأسماء**: النمطُ يبقى على حقله كما هو — إنجليزيٌّ حيث
 * وُجد `name_en`، وعربيٌّ حيث لم يوجد. **هذا يصلح كيف تُرسم، لا أيَّها تُعرض.**
 */
import mapboxgl from "mapbox-gl";

/** **يُخدَم من أصلنا**، ويُزامنه `npm run check:rtl` مع الحزمة المثبَّتة. */
const RTL_PLUGIN_URL = "/vendor/mapbox-gl-rtl-text.js";

if (mapboxgl.getRTLTextPluginStatus() === "unavailable") {
  mapboxgl.setRTLTextPlugin(
    RTL_PLUGIN_URL,
    (error) => {
      // **يُقال ولا يُبتلع**: سقوطُه يعني خريطةً بأسماءٍ مقلوبة، وهو عطبٌ
      // مرئيٌّ للراكب — وابتلاعُه يجعله يُقرأ «هكذا تبدو العربية».
      if (error) console.error("[map-rtl] تعذّر تحميل ملحق العربية:", error);
    },
    // **لا كسل**: التحميلُ المؤجَّل يرسم الإطارَ الأول مقلوباً ثم يصحّحه،
    // فيرى المستخدمُ ارتجافةً — والفرقُ ١٣٣ ك.ب مرّةً واحدة.
    false,
  );
}
