/** **تمييزُ العدد في العربية — بيتٌ واحدٌ لكلِّ جملةٍ تعدّ** (قِيس ٢٠٢٦-٠٩-٠٥).
 *
 * **العلّةُ مقيسةٌ على الشاشة لا مفترضة**: قياسُ الإرسال الجماعيِّ إلى ثلاثة
 * حساباتٍ أعطى «رسالةٌ إلى 3 **حساباً**» و«أُرسلت إلى 3 **صندوقَ** وارد» —
 * **وكلاهما خطأٌ نحويّ**. و«قياسُ الحساب الواحد» الذي سبقه لم يكن ليكشفه:
 * بواحدٍ تُخفي الجملةُ عيبَها.
 *
 * **والقاعدةُ ليست رأياً**: التمييزُ في العربية يحكمه **آخِرُ عددين**:
 *
 *   ١        → مفردٌ بلا عددٍ منطوق   «حسابٌ واحد»
 *   ٢        → مثنّى بلا عددٍ منطوق   «حسابان»
 *   ٣–١٠     → **جمعٌ مجرور**          «٣ حسابات»
 *   ١١–٩٩    → **مفردٌ منصوب**         «١٧ حساباً»
 *   وما بقي  → **مفردٌ مجرور**         «١٠٠ حساب» · «١٠١ حساب»
 *
 * **والمنصوبُ المفردُ هو ما كان مكتوباً للأعداد كلِّها** — صحيحٌ من ١١ إلى ٩٩
 * وخطأٌ فيما عداها. **وهو صنفُ «الصحيحِ بالصدفة»**: من يقرأ الجملةَ بعددٍ في
 * ذلك المدى يراها سليمة، فلا يُراجَع ما تحتها.
 *
 * **والعددُ لاتينيٌّ دائماً** — يمرّ من `digits` كأيِّ رقمٍ يُعرض، ولا يُكتب
 * في الواحد والاثنين لأن العربية لا تنطقه فيهما.
 *
 * **ولا يُخترع شكلٌ عند النداء**: الأشكالُ الخمسةُ تُصرَّح مع الاسم، فمن أضاف
 * جملةً جديدةً كتب أشكالَها مرّةً في موضعها بدل أن يخمّن في كلِّ نداء.
 */
export type CountedForms = {
  /** «حسابٌ واحد» — بلا عددٍ منطوق */
  one: string;
  /** «حسابان» — بلا عددٍ منطوق */
  two: string;
  /** «حسابات» — جمعٌ مجرور، لِـ٣–١٠ */
  few: string;
  /** «حساباً» — مفردٌ منصوب، لِـ١١–٩٩ */
  many: string;
  /** «حساب» — مفردٌ مجرور، لِـ١٠٠ وما بعدها */
  bare: string;
};

export function counted(n: number, forms: CountedForms): string {
  // **آخِرُ عددين هما الحاكم** — ولذلك `101` تأخذ حكمَ `1` لا حكمَ `11`.
  const tail = n % 100;
  if (n === 0) return `${digits(0)} ${forms.few}`;
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  if (tail >= 3 && tail <= 10) return `${digits(n)} ${forms.few}`;
  if (tail >= 11 && tail <= 99) return `${digits(n)} ${forms.many}`;
  return `${digits(n)} ${forms.bare}`;
}

