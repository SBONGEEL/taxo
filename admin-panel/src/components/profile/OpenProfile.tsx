/** «افتح الملفّ» من أيِّ صفٍّ يخصّ إنساناً — **الشقُّ الثاني من §39٫١٢٫٤**.
 *
 * **نصُّ البند**: «**ومن أيِّ صفٍّ يخصّ مستخدماً زرٌّ يفتح ملفَّه مباشرة**».
 *
 * ## ولمَ مكوّنٌ واحدٌ لا زرٌّ في كلِّ جدول
 *
 * **الوجهةُ ليست سطراً واحداً**: الراكبُ يُفتح بـ`users.id` من `/riders`،
 * **والكبتنُ بـ`drivers.id` من `/drivers` ومعه رقمُه في `q`** لأن لا بابَ يقرأ
 * صفَّ كبتنٍ واحد. **وأربعةُ جداولَ تكتب هذا بيدها تفترق أوّلَ تعديل** — وهو
 * الشكلُ الثامن الذي أنشأ `Picker` و`MoneyField` قبله.
 *
 * **وخلطُ المعرّفين يفتح ملفَّ إنسانٍ آخر ولا يصيح شيء**: كلاهما UUID،
 * **فالنوعُ هنا هو ما يمنعه** — `kind` إمّا `"rider"` أو `"driver"`،
 * ولا قيمةَ ثالثة.
 *
 * ## والنصُّ «الملفّ» لا «ملفَّه»
 *
 * **بلا تصنيفِ جنس**: الصفُّ قد يخصّ رجلاً أو امرأة، **وزرٌّ مذكَّرٌ على صفِّ
 * «هناء السائقة» خطأٌ يُقرأ إهمالاً** — ودرسُ `tests/test_label_gender.py`
 * بعينه في ثوبِ زرّ.
 */

import { useNavigate } from "react-router-dom";

export function OpenProfile({
  kind,
  id,
  search,
  className,
}: {
  /** **الوجهةُ لا الدور**: أيُّ ملفٍّ يُفتح، لا ماذا يكون هذا الإنسان. */
  kind: "rider" | "driver";
  /** `users.id` للراكب، **و`drivers.id` للكبتن** — ولا يُخلطان. */
  id: string;
  /** **ما يُضيَّق به قبل الفتح** — رقمُه أو اسمُه.
   *
   * **ولا بابَ يقرأ صفَّ كبتنٍ واحد**، فالدرجُ يُفتح بمطابقة `drivers.id`
   * **داخل القائمة المرشَّحة**. **وقائمةٌ بلا ترشيحٍ تعرض أوّلَ خمسين**
   * — فمن كان خارجها لا يُفتح ملفُّه أبداً، **ولا يصيح شيء**.
   *
   * **والاسمُ يكفي حين لا هاتف**: بحثُ الكباتن يطابق الاسمَ والرقمَ معاً
   * (`admin_search.person_clause`). */
  search?: string | null;
  className?: string;
}) {
  const navigate = useNavigate();

  return (
    <button
      type="button"
      onClick={(event) => {
        // **الصفُّ نفسُه قد يكون زرّاً** (سجلُّ الرحلات يفتح الرحلةَ بالنقر)،
        // **فبلا هذا يفتح النقرُ الاثنين معاً** ويُقرأ الثاني عطباً في الأول
        event.stopPropagation();
        navigate(
          kind === "rider"
            ? `/riders?open=${id}`
            : `/drivers?open=${id}&q=${encodeURIComponent(search ?? "")}`,
        );
      }}
      className={className ?? "text-11 font-semibold text-muted underline"}
    >
      الملفّ
    </button>
  );
}
