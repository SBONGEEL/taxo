/** تغليفُ لوحة الإدارة في APK — **غلافٌ حول اللوحة نفسِها** (قرارُ المالك
 *  2026-09-01).
 *
 * **ولا مشروعٌ رابع**: الغلافُ يحمّل **اللوحةَ نفسَها** من نطاقها بمساراتٍ
 * مخصَّصةٍ للهاتف (`/m/*`). وما ينسخه المشروعُ الرابعُ — الجلسةُ والصلاحياتُ
 * وعقدُ الأخطاء وسلّمُ التصميم — **هو بعينه ما يفترق بعد شهر**.
 *
 * **و`server.url` يعني أن الشاشاتِ تُحمَّل من النطاق لا من داخل الحزمة**،
 * كأخوَيه. وثمنُه مكتوبٌ صراحةً: **التطبيقُ لا يعمل والنطاقُ مغلق** —
 * ومقابلُه أن ما تحقّقنا منه يبقى عاملاً بلا إعادة ضبط.
 *
 * **و`androidScheme: "https"` مقصود**: بلا ذلك يكون المصدرُ
 * `http://localhost` فيُعزَل `localStorage` عن أصلٍ آخر، **فتضيع جلسةُ
 * المشرف بين تشغيلين** — وهي جلسةٌ خلفها تحقّقٌ ثنائيّ.
 *
 * **والقيمُ من `channels.json` لا من هنا**: المعرّفُ والاسمُ وعنوانُ الغلاف
 * تُشتقّ من `TAXO_CHANNEL`، **ولا افتراضَ للقناة** — غيابُها يوقف البناء.
 *
 * **ولا يُنشر على صفحة التحميل**: `private: true` في الجدول، **ويحرسه
 * `tools/check-apk.mjs`** — وقد قِيس بكسرٍ متعمَّد.
 */

import type { CapacitorConfig } from "@capacitor/cli";
import { fromEnv } from "../tools/channels.mjs";

const ch = fromEnv("admin-panel");

const config: CapacitorConfig = {
  appId: ch.appId,
  appName: ch.appName,
  // مطلوبٌ حتى مع `server.url`: الأداةُ تتحقق من وجوده وإن لم تنسخ منه شيئاً
  webDir: "dist",
  android: {
    allowMixedContent: false,
  },
  server: {
    url: ch.shellUrl,
    androidScheme: "https",
    // **لا `cleartext`**: كلُّ شيءٍ خلف HTTPS، وفتحُ النصِّ الصريح هنا يجعل
    // أوّلَ خطأ عنوانٍ يمرّ بلا أن يُرى بدل أن يُرفض
    cleartext: false,
  },
};

export default config;
