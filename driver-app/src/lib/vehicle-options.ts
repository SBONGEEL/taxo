/** سنواتٌ من الأحدث إلى الأقدم — **حدُّها من القاعدة المنشورة لا من هنا**.
 *
 * ويُقلَب الترتيبُ لأن الأحدثَ أكثرُ وقوعاً، ومن يبحث عن ١٩٩٥ يكتبها.
 */
export function vehicleYears(min: number, max: number): string[] {
  const now = new Date().getFullYear();
  // **لا تُعرض سنواتٌ لم تأتِ بعد**: السقفُ المنشور 2100 حدُّ قبولٍ لا قائمةُ
  // اختيار، وعرضُ ٧٥ سنةً قادمةً يدفن السنواتِ الحقيقية.
  const top = Math.min(max, now + 1);
  const out: string[] = [];
  for (let y = top; y >= min; y -= 1) out.push(String(y));
  return out;
}
