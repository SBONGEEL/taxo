/** أطوارُ متابعة الكاميرا الثلاثة (البند ١٧-٢).
 *
 * **وثلاثةٌ لا اثنان**، والفرقُ بين الأخيرين عمليٌّ لا زخرفة:
 *
 * | الطور | الكاميرا | متى يريده الكبتن |
 * |---|---|---|
 * | `free` | لا تتبعه | ينظر إلى ما بعد المنعطف أو يبحث عن عنوان |
 * | `follow` | تتبعه والشمالُ أعلى | يقود في شارعٍ يعرفه ويريد أن يرى نفسه |
 * | `heading` | تتبعه وتدور معه | لا يعرف الطريق، فيريد **ما أمامه أعلى الشاشة** |
 *
 * **والدورانُ ليس تفضيلاً جمالياً**: خريطةٌ شمالُها أعلى تجعل الكبتنَ المتّجهَ
 * جنوباً يقرأ يمينَه يساراً، وهو خطأٌ يقع عند منعطفٍ لا على مهل.
 *
 * **والخروجُ إلى `free` يقع بيده لا بزرّ**: من سحب الخريطةَ أراد النظرَ إلى
 * مكانٍ آخر، وكاميرا تعيده قسراً بعد ثانيةٍ تجعل النظرَ مستحيلاً — وهي أشيعُ
 * شكوى في تطبيقات الملاحة. فالسحبُ نفسُه هو الأمر.
 */

export type FollowMode = "free" | "follow" | "heading";

/** الدورةُ عند الضغط — **ومن `free` يعود إلى `follow` لا إلى `heading`**.
 *
 * فمن ضغط بعد أن سحب يريد **أن يجد نفسَه**، لا أن تدور الخريطةُ تحته فجأةً
 * وهو ينظر إلى شارعٍ بعيد.
 */
export function nextMode(current: FollowMode): FollowMode {
  if (current === "free") return "follow";
  if (current === "follow") return "heading";
  return "follow";
}

export function labelFor(mode: FollowMode): string {
  if (mode === "heading") return "الخريطة تدور مع اتجاهك";
  if (mode === "follow") return "الخريطة تتبعك";
  return "اعرض موقعي";
}
