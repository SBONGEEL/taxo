/** عنوانُ ملفِّ الرسمة — **مبنيٌّ في مكانٍ واحد**.
 *
 * ويقبل عنواناً مطلقاً كما هو: يومَ تُرفع الرسماتُ إلى مخزنٍ خارجيٍّ تصير
 * الحقولُ مطلقةً، فلا يحتاج ذلك تعديلَ سطرٍ هنا.
 */
export function skinAssetUrl(path: string): string {
  if (/^https?:\/\//i.test(path)) return path;
  return `${BASE_URL}${path.startsWith("/") ? "" : "/"}${path}`;
}

/** **أين تُرى هذه المركبة** — جملةٌ تُقرأ قبل الدفع لا بعده.
 *
 * **وتُقرأ من `visible_before_accept` لا من الندرة** (شرطُ العقد): الحقلُ
 * مكتوبٌ في الصفّ ويضبطه المشرف، واستنتاجُه من الندرة يجعل أوّلَ استثناءٍ
 * يقرّره المشرفُ كذبةً على بطاقةِ بيع.
 */
export function visibilityNote(skin: VehicleSkin): string {
  return skin.visible_before_accept
    ? "تظهر لكلِّ راكبٍ حولك على الخريطة، وفي رحلتك."
    : "تظهر لراكبك بعد قبول الرحلة — لا على الخريطة قبلها.";
}

/** **مقاسُ العلامة على الخريطة — ثابتٌ في الكود مهما كان مقاسُ الملف.**
 *
 * ٣٤ بكسل CSS: هو بعينه مقاسُ السهم الذي كان يشغل هذا الموضع، فلا يتبدّل
 * وزنُ العلامة البصريُّ بتبديل المركبة. **والملفُّ لا يقرّر**: رسمةٌ بمقاس
 * ٥١٢ ورسمةٌ بمقاس ٦٤ تخرجان بالمقاس نفسِه، وإلا صار حجمُ سيارةِ الكبتن على
 * خريطته أثراً جانبياً لمن صدّر الملف.
 *
 * **والنسبةُ وحدَها تضربه** (`map_scale_percent` ٨٠–١٢٠٪ يضبطها المشرفُ بعد
 * المعاينة) — فسيارةٌ طويلةٌ ضيّقةٌ تُوزَن بعد أن تُرى، لا بالتخمين.
 */
export const MAP_MARKER_PX = 34;

/** مقاسُ العلامة بالبكسل بعد النسبة — **يُقصّ إلى مدى العقد** (٨٠–١٢٠٪).
 *
 * والقصُّ ليس احتياطاً زائداً: الحقلُ محروسٌ في المخطط وفي القاعدة، **وصفٌّ
 * قديمٌ سبق الحدّ** أو ردٌّ من نسخةٍ أقدم يخرج علامةً تملأ الشاشة أو تختفي.
 */
export function markerPx(scalePercent: number): number {
  const clamped = Math.min(120, Math.max(80, Math.round(scalePercent)));
  return Math.round((MAP_MARKER_PX * clamped) / 100);
}
