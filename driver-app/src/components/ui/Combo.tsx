/** حقلٌ بقائمةِ اقتراحات — **يُنتقى منها أو يُكتب فيه** (البند د).
 *
 * **و`datalist` لا قائمةٌ مبنيّةٌ بيدنا**، لثلاثة أسباب مقيسة لا مفضَّلة:
 *
 * ١) **يعطي الاثنين معاً بلا حالةٍ إضافية**: النظامُ يعرض المطابقَ وهو يكتب،
 *    ويقبل ما ليس في القائمة. وقائمةٌ نبنيها بأنفسنا تحتاج فتحاً وإغلاقاً
 *    وتنقّلاً بلوحة المفاتيح و«خارج النقر يُغلق» — أربعةُ أبوابٍ لعطبٍ في
 *    شيءٍ يعطيه المتصفّح.
 * ٢) **ولا يحبس أحداً**: كبتنٌ يقود مركبةً ليست في قائمتنا يكتبها — وقائمةٌ
 *    مغلقةٌ تعني تسجيلاً لا يتمّ لأن سيارتَه لم تخطر ببالنا.
 * ٣) **ولا يكسر ما هو مبنيّ**: العنصرُ يبقى `<input>` بحرفه، فيرثه `Field`
 *    بحدِّه الأحمر و`aria-invalid` و`aria-describedby` كما هي — ولا تُعاد
 *    كتابةُ رسائل الخطأ لعنصرٍ جديد.
 *
 * **وحدُّه يُقال ولا يُسكت عنه**: `datalist` **لا يُرسم في كلِّ متصفّح بالشكل
 * نفسِه**، وبعضُ الأغلفة لا تعرضه أصلاً. **ولذلك القائمةُ اقتراحٌ لا شرط** —
 * والحقلُ يعمل كاملاً بلا أن يُعرض منها شيء.
 */
import { useId } from "react";

import { Field } from "@/components/ui/Field";

type Props = Omit<React.ComponentProps<typeof Field>, "list"> & {
  /** الاقتراحاتُ — وفارغةٌ تعني حقلاً عادياً بلا قائمة. */
  options: readonly string[];
};

export function Combo({ options, ...rest }: Props) {
  const listId = `${useId()}-options`;
  return (
    <>
      <Field {...rest} list={options.length > 0 ? listId : undefined} />
      {options.length > 0 ? (
        <datalist id={listId}>
          {options.map((option) => (
            <option key={option} value={option} />
          ))}
        </datalist>
      ) : null}
    </>
  );
}
