DRAFTS = (
    (PolicyDocType.PRIVACY_POLICY, PolicyApp.RIDER, RIDER_PRIVACY),
    (PolicyDocType.TERMS_OF_USE, PolicyApp.RIDER, RIDER_TERMS),
    (PolicyDocType.PRIVACY_POLICY, PolicyApp.DRIVER, DRIVER_PRIVACY),
    (PolicyDocType.TERMS_OF_USE, PolicyApp.DRIVER, DRIVER_TERMS),
)


async def seed_policy_drafts(session: AsyncSession) -> int:
    """يكتب المسوّداتِ الغائبةَ وحدَها — **ولا يلمس ثلاثيّةً فيها صفّ**.

    **فمراجعةُ إنسانٍ لا تُدفَن تحت نسخةٍ آلية**: من كتب نسخةً ثانيةً في اللوحة
    ثمّ شغّل هذا السكربتَ لا يجد نسخةً ثالثةً فوقها.
    """
    written = 0
    for country in MARKETS:
        for doc_type, app, body in DRAFTS:
            existing = await session.scalar(
                select(PrivacyPolicy).where(
                    PrivacyPolicy.country_code == country,
                    PrivacyPolicy.doc_type == doc_type,
                    PrivacyPolicy.app == app,
                )
            )
            if existing is not None:
                _log(f"  · {country.value}/{doc_type.value}/{app.value} — موجودةٌ، تُترك")
                continue
            policy = await policies_service.create_version(
                session,
                country=country,
                doc_type=doc_type,
                app=app,
                body_ar=body.strip() + "\n",
                body_en=None,
                # **مسوّدةٌ أولى، ولا تُوسَم «تغييراً جوهرياً»**: لا أحدَ وافق
                # على شيءٍ قبلها، والوسمُ يُقرأ حكماً على نصٍّ لم يُراجَع بعد
                requires_reconsent=False,
            )
            _log(
                f"  ✓ {country.value}/{doc_type.value}/{app.value} — "
                f"نسخة {policy.version}، مسوّدةٌ غيرُ منشورة"
            )
            written += 1
    return written


async def main() -> None:
    _log("مسوّداتُ السياسات والشروط (البند ١٠) — لا يُنشر منها شيء:")
    async with SessionLocal() as session:
        written = await seed_policy_drafts(session)
        await session.commit()
    await engine.dispose()
    _log(f"تم — كُتبت {written} مسوّدة. والنشرُ من اللوحة بعد المراجعة.")


if __name__ == "__main__":
    asyncio.run(main())
