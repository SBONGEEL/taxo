"""صفوفُ اللوحة التي تحمل إنساناً — الدفعةُ وطلبُ الصرف (§٤٧٫١٩، ٢٠٢٦-٠٩-٠٤).

## العلّةُ مكتوبةٌ في §٤٧٫١٧ ومقيسة

«**المدفوعات · النزاعات · طلباتُ الصرف** — **صفرُ معرّفِ إنسانٍ في أنواع
صفوفها**، **والوصلُ يقتضي حقلاً جديداً في العقد**». وهذا هو ذلك الحقل.

## ولمَ نوعٌ يرث لا حقولٌ تُضاف إلى `PaymentOut`

**`PaymentOut` و`WithdrawalOut` يقرؤهما الراكبُ والكبتن** — `routers/payments.py`
و`routers/wallet.py` ينشرانهما لصاحب الحساب. **فحقلٌ يحمل اسمَ الطرف الآخر
ورقمَه فيهما كشفُ هوية**: راكبٌ يقرأ دفعتَه فيرى اسمَ كبتنه ورقمَه، **ولا
شاشةَ طلبت ذلك**.

**وهو قرارُ `live_map.drivers_now` نفسُه** المكتوب في `ARCHITECTURE.md`:
«a separate function with a separate schema rather than the same one with an
`include_identity` flag». **ومفتاحٌ داخل دالّةٍ واحدةٍ يُنسى مرّةً فيتسرّب**،
والنوعُ المنفصلُ لا يُنسى لأنه لا يُكتب إلا حيث يُقصد.

## وما لا يُنشر هنا، بقصد

**لا بريدَ ولا عنوانَ ولا رصيد** — الصفُّ يحمل **ما يُفتح به الملفُّ ويُضيَّق**:
الاسمُ والرقمُ والمعرّف. **وعمودٌ محضَّرٌ لخمسين صفّاً لا يُقرأ منه واحدٌ له
ثمنُه** (§5-ج).
"""

from __future__ import annotations

from pydantic import ConfigDict

from app.schemas.party import DriverPartyOut, PartyOut
from app.schemas.payment import PaymentOut
from app.schemas.wallet import WithdrawalOut


class AdminPaymentRow(PaymentOut):
    """دفعةٌ في اللوحة **ومعها طرفا رحلتها** — شاشتا «المدفوعات» و«النزاعات».

    **والشاشتان تقرآن البابَ نفسَه** (`GET /admin/payments`)، فحقلٌ يُضاف هنا
    يصلهما معاً — **وهو ما يمنع أن تُوصَل إحداهما وتُنسى الأخرى**.
    """

    #: راكبُ الرحلة — **وليس بالضرورة الدافع**: الدفعُ المختلط صفّان، والبطاقةُ
    #: قد تكون بطاقةَ غيره. **فالحقلُ يُسمّى بما هو**: طرفُ الرحلة لا الدافع.
    rider: PartyOut | None = None
    #: كبتنُ الرحلة — **و`None` واقعةٌ حقيقية**: رحلةٌ أُلغيت قبل القبول لا كبتنَ
    #: لها، ورسمُ إلغائها دفعةٌ بلا كبتن.
    driver: DriverPartyOut | None = None


class AdminWithdrawalRow(WithdrawalOut):
    """طلبُ صرفٍ **ومعه صاحبُه**.

    **و`driver_id` كان موجوداً قبل اليوم ولا يكفي**: لا بابَ يقرأ صفَّ كبتنٍ
    واحد، **فالدرجُ يُفتح بمطابقة `drivers.id` داخل القائمة المرشَّحة** —
    **وقائمةٌ بلا ترشيحٍ تعرض أوّلَ خمسين**، فمن كان خارجها لا يُفتح ملفُّه
    أبداً **ولا يصيح شيء**. **فالاسمُ والرقمُ هما ما يُضيَّق به.**

    **وجدولُ الصرف لم يكن يعرض إنساناً البتّة** — أعمدتُه المبلغُ والقناةُ
    والحالُ والتاريخ. **فهذا الحقلُ يفتح عموداً لم يكن**، وهو تغييرُ شكلِ
    جدولٍ بقصدٍ لا وصلُ زرٍّ فحسب.
    """

    model_config = ConfigDict(from_attributes=True)

    #: **غيرُ اختياريّ**: `withdrawal_requests.driver_id` عمودٌ `NOT NULL`
    #: بمرجعٍ `RESTRICT` — **فطلبُ صرفٍ بلا كبتنٍ لا يقع**، واختياريّةٌ هنا
    #: تكذب على القارئ وتجعل الواجهةَ تحرس ما لا يحدث.
    driver: DriverPartyOut


# ═══════════ وأبوابُ الفعل تبقى على `WithdrawalOut` كما هي — **بقياس**
#
# `approve` · `reject` · `paid` · `payout` **تردّ الصفَّ بلا طرفه، ولا يُقرأ
# ذلك نقصاً**: `Finance.tsx::run` ينادي `await load()` **بعد كلِّ فعل**،
# **فحمولةُ الجواب تُطرح ولا تُقرأ**. وقِيس من الشيفرة لا من الظنّ.
#
# **وتوسيعُها كان سيبني شكلاً ثانياً لجوابِ الصرف** (`WithdrawalPayoutOut`
# قائمٌ سلفاً) — **ونسختان لشيءٍ واحدٍ تفترقان أوّلَ تعديل**، وهو ما يمنعه
# الشكلُ الثامن. **فالقوائمُ وحدَها هي التي تحمل الطرف.**
