"""حمولةُ البحث العامّ — **سطرٌ واحدٌ لكلِّ إصابةٍ مهما كان صنفُها** (§39٫١٢٫٤).

**ولمَ قائمةٌ مسطَّحةٌ لا أربعُ قوائم**: الدرجُ يُقرأ من أعلاه إلى أسفله،
**وأربعُ قوائمَ في حمولةٍ واحدةٍ تُجبر الواجهةَ على ترتيبها بيدها** — فتفترق
عن أختها أوّلَ شاشةٍ تُضاف. والصنفُ حقلٌ في السطر، فالواجهةُ تجمعه إن شاءت.

**والشكلُ هو شكلُ `PickerOption` نفسُه** (`id` · `label` · `hint`) **بزيادة
`kind`** — فالدرجُ يُرسم بمكوّن `Picker` القائم لا بمكوّنٍ ثانٍ بجانبه
(§39٫١٢٫٨).
"""

from __future__ import annotations

import uuid
from typing import Literal

from pydantic import BaseModel

#: **أصنافُ الإصابة** — وليست تعداداً في القاعدة: لا جدولَ اسمُه «صنفُ إصابة».
#: **وهي وجهةٌ لا حال**: كلُّ صنفٍ يقول إلى أيِّ شاشةٍ يقفز الدرج.
SearchKind = Literal["user", "driver", "ride", "claim"]


class SearchHit(BaseModel):
    """إصابةٌ واحدة — **معرّفٌ للآلة، واسمٌ وتمييزٌ للإنسان**."""

    kind: SearchKind
    #: **معرّفُ الوجهة لا معرّفُ الحساب دائماً**: للكبتن `drivers.id`
    #: لأن ملفَّه يُفتح به، وللحساب `users.id`. **وخلطُهما يفتح ملفَّ إنسانٍ
    #: آخر** — وهو ما يحرسه `admin_search._must_point_at` في الشرط.
    id: uuid.UUID
    #: السطرُ الأول — الاسمُ أو المرجعُ أو معرّفُ الرحلة
    label: str
    #: السطرُ الثاني — ما يفرّق متشابهَي الاسم: رقمٌ أو حالٌ أو صاحبٌ
    hint: str | None = None


class SearchHits(BaseModel):
    hits: list[SearchHit]
