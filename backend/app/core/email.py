"""تطبيعُ عناوين البريد — **بيتٌ واحدٌ كـ`core/phone.py`**.

`ARCHITECTURE.md` يقول عن الهاتف: «Phone number is the login identity and is
always stored as E.164 … Never query `users.phone` with raw client input».
**والبريدُ يحتاج القاعدةَ نفسَها لعلّةٍ أقربَ منها**: `Ali@X.com` و`ali@x.com`
**صندوقٌ واحد**، فبحثٌ بالنصِّ الخام يجد أحدَهما ولا يجد الآخر — **فيُنشأ
حسابٌ ثانٍ على بريدٍ واحد**، وهو بعينه ما وقع مرّةً على رقمٍ في هذا المشروع.

## ولا `EmailStr` من pydantic — **بقرارٍ مكتوب لا سهو**

`EmailStr` يحتاج حزمةَ `email-validator`، **وهي غيرُ مثبَّتةٍ في الصورة**.
وإضافةُ تبعيّةٍ في الجولة التي تُضاف فيها قناةٌ **فعلان يمسّان سطحاً واحداً**،
ومعها فخُّ الحاويات المسجَّل في `CLAUDE.md`: **المجموعةُ تخضرّ والخادمُ الحيُّ
يسقط**، لأن `docker compose run` يبني حاويةً جديدةً من الصورة بينما الخدمةُ
الطويلةُ تبقى على القديمة. **وقد شُحن ذلك مرّةً** (`python-multipart`، المرحلة
9-ب) فأجاب كلُّ طلبٍ بخطأ حتى أُعيد إنشاءُ الحاوية.

## وما يفحصه هذا الملفّ — **بحدِّه**

**شكلٌ لا وجود.** `a@b.c` يمرّ ولو لم يكن هناك صندوق — **ولا شيءَ في الدنيا
يعرف أن صندوقاً موجودٌ إلا رسالةٌ تصله**. **وهذا هو التحقّق**: الرمزُ يصل أو
لا يصل، **والفحصُ هنا يمنع الخطأَ المطبعيَّ الصريح لا أكثر**.

**ولا يُدّعى غيرُ ذلك**: مُحقِّقٌ يزعم أنه يعرف صحّةَ العنوان **يرفض عناوينَ
صحيحةً نادرة** ويقبل مئةَ عنوانٍ لا صندوقَ لها — فيدفع ثمناً بلا مقابل.
"""

from __future__ import annotations

import re

from app.core.exceptions import InvalidInput

#: طولُ العمود في `users.email` — والحدُّ هنا كي يُرفض بنصٍّ لا بخطأ قاعدة
MAX_LENGTH = 320

# **شكلٌ عمليٌّ لا RFC 5322**: محرفٌ واحدٌ على الأقل قبل `@`، ونطاقٌ بنقطةٍ
# واحدةٍ على الأقل ولاحقةٍ من حرفين فأكثر. **ولا مسافاتٌ ولا `@` ثانية.**
_SHAPE = re.compile(r"^[^@\s]+@[^@\s.]+(\.[^@\s.]+)+$")


def normalize_email(raw: str) -> str:
    """يُطبّع عنواناً ويرفض ما ليس عنواناً — **والمخرَجُ هو ما يُخزَّن ويُقارَن**.

    **والتصغيرُ للعنوان كلِّه**: النطاقُ غيرُ حسّاسٍ للحالة بالمعيار، والجزءُ
    قبل `@` حسّاسٌ نظريّاً — **ولا مزوّدَ يُعتدّ به يفرّق فيه عملياً**،
    **وحفظُ الحالة يفتح بابَ حسابين على صندوقٍ واحد**. فالمقايضةُ محسومةٌ
    للجهة التي تمنع الازدواج.
    """
    value = (raw or "").strip().lower()
    if not value:
        raise InvalidInput("البريد الإلكتروني مطلوب")
    if len(value) > MAX_LENGTH:
        raise InvalidInput("البريد الإلكتروني أطول من المسموح")
    if not _SHAPE.match(value):
        raise InvalidInput("البريد الإلكتروني غير صالح — تحقّق من كتابته")
    return value
