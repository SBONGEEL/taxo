"""خاناتٌ لاتينيةٌ في كلِّ نصٍّ يكتبه إنسانٌ ثمّ ننشره (قرارُ المالك: «الأرقامُ لاتينية في كلِّ مكان»).

**النصُّ الحرُّ يُطبَّع عند الكتابة لا عند العرض**: عنوانُ مستلمٍ كُتب «بناية ٤» يصل الكبتنَ «بناية 4» كما يُرسم كلُّ رقمٍ في التطبيقين —
**وأمسكه حارسُ النصّ المنشور** (`tests/digit_format.py`) أوّلَ ما نُشر عنوانُ طرد. والتطبيعُ هنا لا في كلِّ واجهة: واجهتان تطبّعان
بلفظين تفترقان.
"""

from __future__ import annotations

_TO_LATIN = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")


def latin_digits(text: str) -> str:
    return text.translate(_TO_LATIN)
