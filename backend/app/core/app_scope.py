"""أيُّ تطبيقٍ يطلب الجلسة — **وأيُّ الأدوار يدخله** (قرارُ المالك 2026-08-15).

**العطبُ الذي وُجد لأجله**: بياناتُ كبتنٍ كانت تفتح تطبيقَ الراكب. يُصدر
`POST /auth/login` جلسةً لأيِّ دورٍ كان، ولا يقول العميلُ أيَّ تطبيقٍ هو، ولا
يسأل أيُّ تطبيقٍ عن الدور — فيدخل الكبتنُ تطبيقَ الراكب فيرى شاشاتِ راكبٍ
تُجيبه ٤٠٣ في كل باب، ويدخل **المشرفُ** تطبيقَ الركّاب بجلسةٍ كاملة. وقرارُ
المالك: **كلُّ تطبيقٍ لدوره وحده، و`admin`/`support` لا يدخلان تطبيقَي الراكب
والكبتن**.

**والرفضُ في الخلفية لا في الواجهة**: شرطٌ في الشاشة يزول بتعديل ملفٍ في
المتصفح، والبابُ الذي تُصدَر منه الجلسةُ واحد.

**ودعوى العميل هنا مقبولةٌ لأنها تضييقٌ لا توسيع.** القاعدةُ المكتوبة في
`card_gateway.return_url_for` أن التطبيق يُشتقّ من الدور ولا يُصدَّق فيه
العميل — وهي في محلِّها هناك: هناك يُختار **عنوانٌ يُرسَل إليه المال**،
فادّعاءٌ كاذبٌ يوجّهه. وهنا لا يكسب الكاذبُ شيئاً: من أعلن «أنا تطبيقُ
الكبتن» ودورُه كبتنٌ نال ما دورُه يعطيه أصلاً، ومن أعلن غيرَ دوره رُفض. فأسوأُ
ما يفعله كاذبٌ بهذا الحقل أن يمنع نفسَه.

**وما لا يفعله**: ليس بديلاً عن `RiderUser`/`CurrentDriver`/`require_roles` —
تلك تحرس **ما يُفعل** لا **أين يُدخل**. وهذا يحرس بابَ الدخول وحده، فيمنع
لبسَ الأدوار لا يُبدّل حراسةَ المسارات.
"""

from __future__ import annotations

from app.core.exceptions import AppError
from app.models.enums import AccountKind, ClientApp, UserRole

# **`ClientApp` انتقل إلى `models/enums.py` ويُعاد تصديرُه من هنا** (البند ٨،
# §43): صار **عموداً في `app_releases`**، **ونموذجٌ يستورد من `core/` يقلب
# الطبقات**. والاسمُ هنا كما كان، فلا مستوردَ تغيّر.
__all__ = ["ClientApp", "account_kind_for", "guard"]


# **قرارُ المالك حرفياً**: لكلِّ تطبيقٍ دورُه وحدَه، و`admin`/`support` في
# اللوحة فقط. ولا يُوسَّع هذا الجدولُ «تسهيلاً على المشرف»: مشرفٌ يدخل تطبيقَ
# الراكب يرى شاشاتٍ بُنيت لراكبٍ ويُفتي عن تجربةٍ ليست تجربتَه.
_ROLES: dict[ClientApp, frozenset[UserRole]] = {
    ClientApp.RIDER: frozenset({UserRole.RIDER}),
    ClientApp.DRIVER: frozenset({UserRole.DRIVER}),
    ClientApp.PANEL: frozenset({UserRole.ADMIN, UserRole.SUPPORT}),
}

# نصُّ الرفض يقول **أين يذهب**، لا «ممنوع» وحدها: من كتب بياناته الصحيحة في
# تطبيقٍ خطأ يظن الحسابَ معطوباً فيسجّل حساباً ثانياً بنفس الرقم — وتلك واقعةٌ
# مسجَّلةٌ في هذا المشروع (الفخُّ الثاني في «الحسابات الخمسة»)
_WHERE: dict[UserRole, str] = {
    UserRole.RIDER: "هذا حسابُ راكب — ادخل من تطبيق تكسي الراكب",
    UserRole.DRIVER: "هذا حسابُ كبتن — ادخل من تطبيق الكبتن",
    UserRole.ADMIN: "هذا حسابٌ إداري — ادخل من لوحة التشغيل",
    UserRole.SUPPORT: "هذا حسابُ دعم — ادخل من لوحة التشغيل",
}


class WrongAppForRole(AppError):
    """دورٌ لا يدخل هذا التطبيق — 403 لا 401: البياناتُ صحيحةٌ والبابُ خطأ."""

    status_code = 403
    code = "wrong_app_for_role"


# ترتيبُ اختيار النصّ عند الرفض — الأوضحُ للقارئ أولاً
_ROLES_ORDER: tuple[UserRole, ...] = (
    UserRole.DRIVER,
    UserRole.RIDER,
    UserRole.ADMIN,
    UserRole.SUPPORT,
)


def guard(roles: UserRole | frozenset[UserRole], app: ClientApp | None) -> None:
    """يرفض من لا يملك دوراً ينتمي إلى التطبيق الطالب.

    **وتوسيعُ الأدوار لا يوسّع نطاقَ التطبيقات** (شرطُ المالك 2026-08-19):
    كلُّ تطبيقٍ ما زال يخدم دورَه وحدَه، وما تغيّر أن السؤالَ صار «أيملك دوراً
    يدخل هنا؟» بدل «أدورُه هو؟». فمن يملك الدورين يدخل التطبيقين — وهذا هو
    المقصود؛ ومن لا يملك دورَ تطبيقٍ يُرفض كما اليوم بلا فرق.

    `app=None` يعني عميلاً لم يُعلن — أدوات الفحص و`curl` والعملاء الأقدم من
    هذا الحارس — **فيمرّ**: هذا يمنع لبسَ الأدوار في تطبيقاتنا الثلاثة، وليس
    بابَ مصادقةٍ ثانياً. وحصرُه في العملاء المعلنين هو ما يجعل إضافتَه اليومَ
    لا تُخرج أحداً من جلسةٍ قائمة.
    """
    if app is None:
        return
    owned = frozenset({roles}) if isinstance(roles, UserRole) else frozenset(roles)
    if owned & _ROLES[app]:
        return
    # **النصُّ يقول أين يذهب**، ويُختار من دورٍ واحدٍ يملكه — وأيُّها كان فالوجهةُ
    # صحيحة، لأن من يملك دورَ هذا التطبيق لا يصل هذا السطر أصلاً
    shown = next((role for role in _ROLES_ORDER if role in owned), None)
    raise WrongAppForRole(
        _WHERE.get(shown, "هذا الحساب لا يدخل من هنا") if shown else
        "هذا الحساب لا يدخل من هنا"
    )


#: **أيُّ نوعِ حسابٍ يدخله كلُّ تطبيق** (`SPEC-DELIVERY.md` §D1.4 و§D9.1، 1-أ/4).
#: **خريطةٌ كاملةٌ على `ClientApp`** يحرسها اختبار: تطبيقٌ يُضاف بلا نوعٍ هنا
#: يُحمِّر المجموعة ولا يقع على `taxo` صامتاً. واليومَ التطبيقاتُ الثلاثةُ كلُّها
#: `taxo` — والسوقُ والتاجرُ يُضافان مع قيمتَيهما في `ClientApp` (المرحلة 7).
_ACCOUNT_KIND: dict[ClientApp, AccountKind] = {
    ClientApp.RIDER: AccountKind.TAXO,
    ClientApp.DRIVER: AccountKind.TAXO,
    ClientApp.PANEL: AccountKind.TAXO,
}


def account_kind_for(app: ClientApp | None) -> AccountKind:
    """نوعُ الحساب الذي يعنيه طلبٌ من هذا التطبيق.

    **و`None` ⇒ `taxo`** — عميلٌ لم يُعلن (أدواتُ الفحص والحِزمُ الأقدم) يبقى
    يدخل كما كان يدخل، بالقاعدة نفسِها التي تجعل `guard` يمرّره. **وهي أسبقيةٌ
    معلَنةٌ لا تخمين** (§22): كلُّ حسابٍ قائمٍ `taxo`، ولا تطبيقَ اليومَ لغيره.
    """
    if app is None:
        return AccountKind.TAXO
    return _ACCOUNT_KIND[app]
