"""نطاقُ الخدمة — **حدٌّ بالبلد لا بالمسافة** (قرارُ المالك ٢٠٢٦-٠٩-١٠).

**العطبُ الذي وُجدت له** (قِيس ٢٠٢٦-٠٩-٠٩): الخلفيةُ تقبل رحلةً بلدُها `JO`
ووجهتُها في طرابلس — `32.8935, 13.3669`، على بعد نحو ألفي كيلومتر — وتسعّرها
على المسافة كما هي. **وقِيس أنه يقع على الإنتاج لا على التطوير وحدَه**: ثلاثةٌ
من ستِّ رحلاتٍ أردنيةٍ هناك أحدُ طرفيها خارج البلد.

**والمسارُ الذي يبلغه إنسان**: بحثُ العناوين محدودٌ بـ`country=` فلا يُخرج
عنواناً خارج السوق، **لكنّ «حدّدها على الخريطة بالدبوس» لا حدَّ له** — من
يُبعد الخريطةَ ويضع دبّوساً خارج البلد يحصل على تقديرٍ وطلب.

──────────────────────────────────────────────────────────────────────────────
**والحدُّ بالبلد لا بالمسافة** — وهذا قرارٌ لا تفصيل: **رحلةٌ من العقبة إلى
إربد (نحو ٣٥٠ كم) مشروعةٌ ولا تُمسّ**، ورحلةٌ إلى طرابلس ليست. فلا رقمَ مسافةٍ
في هذا الملفّ إطلاقاً.

**والمرجعُ صندوقٌ يحوي البلدَ كلَّه، ويُرفض ما خرج عنه وحدَه:**

١) **فلا يرفض مشروعاً أبداً** — الصندوقُ يحوي البلد، فكلُّ نقطةٍ داخله داخلَ
   الصندوق بالضرورة. **وحارسٌ يصيح على السليم يُطفأ**، ويسقط معه ما يمسكه حقاً.
٢) **ويمسك طرابلس بيقين** — `13.35` خارج مدى الأردن بأكثرَ من عشرين درجة.
٣) **ولا نداءَ شبكةٍ ولا مال** — أربعةُ مقارناتٍ في المسار الحرج، لا عكسُ
   ترميزٍ من مزوّدٍ عند كلِّ تقدير.

**وحدُّه مكتوبٌ لا مسكوتٌ عنه**: **لا يمسك نقطةً خلف الحدود مباشرة** — ما جاور
الحدَّ من سوريةَ أو فلسطينَ أو السعوديةِ داخلُ الصندوق. من أراد الدقّةَ فطريقُه
مضلَّعٌ يُخزَّن ويُحرَّر، **وهي ميزةٌ لها سطحٌ وقرار، لا إصلاحُ عطب**.

**ولمَ ثابتٌ هنا لا عمودٌ في `map_settings`** (قرارُ المالك ٢٠٢٦-٠٩-١٠):
حدودُ الدولة لا تتغيّر، والرقمُ الوحيدُ الذي قد يتغيّر هو **إضافةُ سوق** —
وهي تمرّ بالشيفرة أصلاً (`CountryCode`). **وزرٌّ يُتيح تعطيلَ حدٍّ أمنيٍّ
بضغطةٍ يخالف «لا إلغاءَ لحارس»**، ومشرفٌ يكتب صندوقاً خاطئاً يوقف سوقاً كاملاً.

**واسمُه `service_area` لا `geo`** — و`app.services.geo` قائمٌ سلفاً لحساب
المسافات والمواقع. **واسمان متشابهان في مسارٍ واحدٍ يُقرأ أحدُهما مكانَ
الآخر**، وهو من عائلة «ثلاثُ تسمياتٍ لشيءٍ واحد» في `GUARDS.md`.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable, Protocol

from app.core.exceptions import OutsideServiceArea, ServiceAreaUndeclared
from app.models.enums import CountryCode


class Point(Protocol):
    """**أيُّ نقطةٍ لها `lat` و`lng`** — بنيةً لا نوعاً بعينه.

    في المسار نوعان بالاسم نفسِه: `services.directions.Coordinates`
    و`CoordinatesIn` في المخطّطات. **وربطُ الحدِّ بأحدهما يجعل البابَ الثاني
    يحتاج تحويلاً**، والتحويلُ موضعٌ ثالثٌ يُنسى.
    """

    lat: float
    lng: float


@dataclass(frozen=True)
class MarketBox:
    """صندوقٌ **يحوي** البلدَ كلَّه — لا يطابق حدودَه."""

    min_lat: float
    max_lat: float
    min_lng: float
    max_lng: float

    def holds(self, lat: float, lng: float) -> bool:
        return (
            self.min_lat <= lat <= self.max_lat
            and self.min_lng <= lng <= self.max_lng
        )


# **الأرقامُ مصدرُها المدى الجغرافيُّ المعلَن للدولتين، موسَّعاً هامشاً**
# — فالمطلوبُ صندوقٌ **يحوي** لا صندوقٌ **يطابق**. وتوسيعُه يزيد ما يمرّ
# ولا ينقص ما يُمنع، **وخطؤه في الاتجاه الآمن**.
MARKET_BOX: dict[CountryCode, MarketBox] = {
    CountryCode.JO: MarketBox(min_lat=29.18, max_lat=33.38, min_lng=34.95, max_lng=39.30),
    CountryCode.LY: MarketBox(min_lat=19.50, max_lat=33.17, min_lng=9.31, max_lng=25.15),
}


def box_for(country_code: CountryCode) -> MarketBox:
    """صندوقُ السوق — **وسوقٌ بلا صندوقٍ يقف ولا يُقرأ سلامة**.

    **صفرٌ مقروءٌ عطبٌ لا سلامة**: لو أعادت هذه الدالّةُ «لا حدَّ» لسوقٍ لم
    يُصرَّح، لكان أوّلُ سوقٍ يُضاف بلا صندوقٍ **مفتوحاً على الأرض كلِّها
    وصامتاً**. واختبارُ الاكتمال يجعل هذه الحالَ غيرَ قابلةٍ للشحن أصلاً.
    """
    try:
        return MARKET_BOX[CountryCode(country_code)]
    except KeyError as exc:  # pragma: no cover — يمنعه اختبارُ الاكتمال
        raise ServiceAreaUndeclared() from exc


def require_inside_market(
    country_code: CountryCode, points: Iterable[Point]
) -> None:
    """**البابُ الواحد** — يناديه التقديرُ والطلبُ معاً.

    **وحارسٌ يقبل في التقدير ويرفض عند التأكيد يجعل الراكبَ يبني على رقمٍ ثم
    يُردّ** — وهو أسوأُ من ألّا يُمنع (نفسُ علّة `reject_stop_at_dropoff`).

    **والطرفانِ والمحطّاتُ تُفحص كلُّها لا الوجهةَ وحدَها**: من اثنتين وستّين
    رحلةً ملوَّثةً على التطوير كان **الانطلاقُ** هو الخارجَ في أربعين.
    """
    box = box_for(country_code)
    for point in points:
        if not box.holds(float(point.lat), float(point.lng)):
            raise OutsideServiceArea(country_code)
