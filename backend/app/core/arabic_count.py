"""**العددُ مع معدوده بالعربيّة** — نسخةُ الخلفيّة من `lib/arabic-count.ts` في التطبيقين (أمرُ المالك ٢٠٢٦-١١-٢٥: «يتبقّى 1 أيام»
⇒ «يتبقّى يوم واحد»).

١ «يوم واحد» · ٢ «يومان» (و«يومين» بعد حرف جرٍّ أو مضاف: `after`) · ٣–١٠ «3 أيام» · ١١–٩٩ «11 يوماً» · ١٠٠ و١٠١ و١٠٢ «100 يوم»
· والصفرُ «0 يوم»؛ **وفوق المئة بآخر خانتين**. **والخاناتُ لاتينيّة** (قرارُ المالك 2026-08-19).

**ولمَ لا يُكتب العددُ في القالب** («بقي لك {n} أيام»): القالبُ يثبّت صيغةً واحدةً لكلِّ عدد، فيصدق على ٣–١٠ ويكذب على غيرها.
"""

from __future__ import annotations

#: (مفرد، مثنّى رفعاً، مثنّى جرّاً، ٣–١٠، ١١–٩٩، الأساس)
UNITS: dict[str, tuple[str, str, str, str, str, str]] = {
    "day": ("يوم واحد", "يومان", "يومين", "{n} أيام", "{n} يوماً", "{n} يوم"),
    "hour": ("ساعة واحدة", "ساعتان", "ساعتين", "{n} ساعات", "{n} ساعةً", "{n} ساعة"),
    "minute": ("دقيقة واحدة", "دقيقتان", "دقيقتين", "{n} دقائق", "{n} دقيقةً", "{n} دقيقة"),
    "ride": ("رحلة واحدة", "رحلتان", "رحلتين", "{n} رحلات", "{n} رحلةً", "{n} رحلة"),
    "point": ("نقطة واحدة", "نقطتان", "نقطتين", "{n} نقاط", "{n} نقطةً", "{n} نقطة"),
}


def count_of(n: int, unit: str, *, after: bool = False) -> str:
    one, two, two_after, few, many, base = UNITS[unit]
    whole = abs(int(n))
    if whole == 1:
        return one
    if whole == 2:
        return two_after if after else two
    tail = whole % 100
    if whole == 0 or tail <= 2:
        return base.format(n=n)
    if tail <= 10:
        return few.format(n=n)
    return many.format(n=n)
