"""**العددُ مع معدوده بالعربيّة** — نسخةُ الخلفيّة من `lib/arabic-count.ts` في التطبيقين (أمرُ المالك ٢٠٢٦-١١-٢٥: «يتبقّى 1 أيام»
⇒ «يتبقّى يوم واحد»).

١ «يوم واحد» · ٢ «يومان» (و«يومين» بعد حرف جرٍّ أو مضاف: `after`) · ٣–١٠ «3 أيام» · ١١–٩٩ «11 يوماً» · ١٠٠ و١٠١ و١٠٢ «100 يوم»
· والصفرُ «0 يوم»؛ **وفوق المئة بآخر خانتين**. **والخاناتُ لاتينيّة** (قرارُ المالك 2026-08-19).

**والصيغُ مفاتيحُ في القاموس الفرنسيّ** (`app/i18n/fr.json`، والملفُّ في `scripts/i18n_extract.py`): «3 أيام» داخل قالبٍ مترجَمٍ
تصير «3 jours» — والموضعُ `{0}` لا `{n}` لأن القاموسَ يطابق `{0}`.

**ولمَ لا يُكتب العددُ في القالب** («بقي لك {0} أيام»): القالبُ يثبّت صيغةً واحدةً لكلِّ عدد، فيصدق على ٣–١٠ ويكذب على غيرها.
"""

from __future__ import annotations

#: (مفرد، مثنّى رفعاً، مثنّى جرّاً، ٣–١٠، ١١–٩٩، الأساس)
UNITS: dict[str, tuple[str, str, str, str, str, str]] = {
    "day": ("يوم واحد", "يومان", "يومين", "{0} أيام", "{0} يوماً", "{0} يوم"),
    "hour": ("ساعة واحدة", "ساعتان", "ساعتين", "{0} ساعات", "{0} ساعةً", "{0} ساعة"),
    "minute": ("دقيقة واحدة", "دقيقتان", "دقيقتين", "{0} دقائق", "{0} دقيقةً", "{0} دقيقة"),
    "ride": ("رحلة واحدة", "رحلتان", "رحلتين", "{0} رحلات", "{0} رحلةً", "{0} رحلة"),
    "point": ("نقطة واحدة", "نقطتان", "نقطتين", "{0} نقاط", "{0} نقطةً", "{0} نقطة"),
}


def count_of(n: int, unit: str, *, after: bool = False) -> str:
    one, two, two_after, few, many, base = UNITS[unit]
    whole = abs(int(n))
    if whole == 1:
        return one
    if whole == 2:
        return two_after if after else two
    tail = whole % 100
    if whole == 0 or tail <= 2:
        return base.replace("{0}", str(n))
    if tail <= 10:
        return few.replace("{0}", str(n))
    return many.replace("{0}", str(n))
