"""**ما لا يمرّ في محادثة الرحلة** — أرقامُ الهواتف والروابط (SPEC §٦٦-أ/٢، `design/APPROVALS-DATA.md` §١).

**دالّةٌ محضة**: لا قاعدةَ ولا شبكة — نصٌّ يدخل وحكمٌ يخرج، فتُقاس بجدولٍ واسعٍ من الصيغ (`tests/test_trip_chat.py`).

## الرقم — **بأيِّ صيغة**

١) **يُطبَّع النصُّ أولاً**: `NFKC` (الأرقامُ العريضة والدائريّة والرياضيّة ← لاتينية) · وكلُّ خانةٍ عشريّةٍ في أيِّ كتابةٍ — العربيةُ
   الهندية `٠-٩` والفارسية `۰-۹` وغيرهما — ← لاتينية · **وتُنزع الأحرفُ الخفيّة** (الصفرية العرض، وعلاماتُ الاتجاه، والتشكيل،
   والتطويل، وما يركب الخانةَ كإطار `0️⃣`): كلُّها تُدسّ بين خانتين فلا تُرى وتقطع العدّ.
٢) **ثمّ يُعدّ أطولُ تتابعٍ من «وحدات الرقم»**: كلُّ خانةٍ وحدة، **وكلمةُ عددٍ** بالعربية (فصحى وعامّية: صفر/زيرو · واحد · اتنين/
   اثنين · تلاتة/ثلاثة · … · تمانية/ثمانية · تسعة) أو بالإنجليزية وحدةٌ أيضاً — **والعشراتُ وحدتان** («تسعين») والمئةُ ثلاث،
   و`double`/`triple` تضاعف ما بعدها.
   **وما بين الوحدات لا يقطع التتابع إلا حرفٌ ليس عدداً، أو `:`** — والقاعدةُ «ما ليس حرفاً ولا خانةً فاصل» لا قائمةُ فواصل:
   - **الفراغُ لا يُعدّ أصلاً** (المسافة · السطرُ الجديد · المسافةُ غيرُ المنكسرة)، **فلا يقطع مهما طال** — «079\\n\\n\\n\\n123» رقم.
   - **وكلُّ ما سواه من غير الحروف والخانات فاصل**: `- . / ( ) _ , ، * | ~ · •` والرموزُ التعبيريّة وما لم يُكتب هنا —
     **حتى ثلاثةٍ متتالية** («079 -- 123»). **وقائمةٌ مصرَّحةٌ كانت هي الثغرة** (قِيس ٢٠٢٦-١٠-٠٨): كلُّ رمزٍ لم يُكتب فيها —
     «·» و«🙂» و«*» و«،» — كان يقطع العدّ، فيمرّ الرقمُ بأيِّ رمزٍ لم يخطر لكاتبها.
   - **وكلمةُ ربطٍ فاصلٌ واحد**: «و» · «ثمّ» · «بعدين» · `and` · `then` («079 ثمّ 123 ثمّ 4567»).
   - **و`:` وحدَه يقطع** — «10:45» وقتٌ لا نصفُ رقم، وهو ما يُكتب بين خانتين في رحلةٍ حقيقيّة.
٣) **سبعُ وحداتٍ فأكثر = رقمُ هاتف**. أقصرُ رقمٍ محلّيٍّ في السوقين سبعُ خانات بلا مفتاح المدينة، **وستٌّ تمرّ** — رمزُ تحقّقٍ يقرؤه
   الراكبُ لكبتنه.

**وما يمرّ عمداً — مقيساً في الاختبار**: سعرٌ «12.500» · وقتٌ «10:45» · لوحةٌ «AMM-1010» · رمزٌ من ستّ خانات · **ولوحةُ مركبة
الرحلة نفسِها** «13-12345» (`allowed` — يمرّرها `trip_chat.send` وحدَها، انظر `check`).
**وما يُردّ بثمنٍ مقبول — ومكتوبٌ لا مسكوتٌ عنه**: تاريخٌ بسنته «8/10/2026» وعنوانُ IP — سبعُ وحداتٍ فأكثر — **وسعران لا يفصل
بينهما إلا فاصلة** («2.500، 3.000»): الفاصلةُ صارت فاصلاً لأن «079 123، 4567» رقم. **والردُّ يقول لماذا**، فيعيد صاحبُه الصياغةَ
بكلمة؛ **ورقمٌ يمرّ لا يُستعاد** — والقاعدةُ من المالك: «لا يُكشف رقمُ هاتفٍ عبر أيٍّ منهما».

## الرابط

`http://` · `https://` · `www.` · **واسمُ نطاقٍ مكشوفٍ بامتدادٍ معروف** (`wa.me` · `t.me` · `bit.ly` · `x.com` · بريدٌ إلكترونيّ…).
**والامتداداتُ قائمةٌ مصرَّحةٌ لا «أيُّ حروفٍ بعد نقطة»**: بها لا يُقرأ «12.500» ولا «a.m.» رابطاً.

## وما لا يمسكه — يُقال

رقمٌ مكتوبٌ بحروفٍ تشبه الخانات (`O` مكانَ الصفر)، أو مقسومٌ على رسائلَ متتالية، أو مفصولٌ بكلمةٍ ليست ربطاً أو بأربعة رموزٍ فأكثر
(«079 ---- 123»)، أو موصوفٌ بجملةٍ («رقمي نفس رقم المحل»). **فالحارسُ يمسك ما يُكتب عادةً لا ما يُموَّه قصداً** — والبلاغُ واللوحةُ
لما يتجاوزه.
"""

from __future__ import annotations

import re
import unicodedata
from collections.abc import Iterable
from enum import StrEnum


class Violation(StrEnum):
    """**القيمتان رمزا الخطأ نفسُهما** — لا «phone»/«link» عاريتين: حارسُ الاتحادات (`check:enums`) يقرأ كلَّ قيمةِ تعدادٍ في الخلفية،
    و«phone» عضوٌ في اتحادات حقول النماذج في التطبيقين فتصير مخلوطةً بلا سبب (قِيس ٢٠٢٦-١٠-٠٨)."""

    PHONE = "chat_phone_number"
    LINK = "chat_link"


#: **سبعُ وحداتٍ فأكثر رقمُ هاتف** — انظر رأسَ الملف
MIN_PHONE_UNITS = 7
#: **أطولُ فاصلٍ لا يقطع التتابع** — ثلاثةُ رموزٍ أو كلماتِ ربطٍ متتالية («079 .. 123»، «079 -و- 123»)، **والفراغُ لا يُعدّ فيها**
MAX_SEPARATOR_RUN = 3

#: **القاطعُ الوحيدُ من غير الحروف** — «10:45» وقتٌ لا رقم. **وكلُّ ما سواه من غير الحروف والخانات فاصل** (انظر رأسَ الملف)
_BREAKERS = frozenset(":")

#: التطويلُ حرفٌ «معدَّل» لا علامةُ تشكيل — يُنزع بالاسم
_TATWEEL = "ـ"

#: **كلماتُ العدد** — بعد تطبيعٍ يوحّد الألفات والتاءَ المربوطة والياء (`_fold`). والقيمةُ عددُ الوحدات التي تقولها الكلمة
_WORD_UNITS: dict[str, int] = {}
for _words, _units in (
    # ٠–٩ فصحى وعامّية
    (("صفر", "زيرو"), 1),
    (("واحد", "واحده", "وحده"), 1),
    (("اثنان", "اثنين", "اتنين", "ثنين", "تنين", "اثنتان", "اثنتين"), 1),
    (("ثلاث", "ثلاثه", "تلات", "تلاته"), 1),
    (("اربع", "اربعه"), 1),
    (("خمس", "خمسه"), 1),
    (("ست", "سته"), 1),
    (("سبع", "سبعه"), 1),
    (("ثمان", "ثماني", "ثمانيه", "تمان", "تماني", "تمانيه", "ثمنيه", "تمنيه"), 1),
    (("تسع", "تسعه"), 1),
    # العشراتُ تقول خانتين («سبعة وتسعين» = 97)
    (("عشر", "عشره", "عشرين", "عشرون"), 2),
    (("ثلاثين", "ثلاثون", "تلاتين"), 2),
    (("اربعين", "اربعون"), 2),
    (("خمسين", "خمسون"), 2),
    (("ستين", "ستون"), 2),
    (("سبعين", "سبعون"), 2),
    (("ثمانين", "ثمانون", "تمانين"), 2),
    (("تسعين", "تسعون"), 2),
    (("ميه", "مئه", "مايه"), 3),
    # English
    (("zero", "oh", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"), 1),
    (
        (
            "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen",
            "nineteen", "twenty", "thirty", "forty", "fifty", "sixty", "seventy", "eighty", "ninety",
        ),
        2,
    ),
    (("hundred",), 3),
    # **«double seven» = خانتان**: «double» تحسب واحدةً والكلمةُ بعدها الثانية
    (("double",), 1),
    (("triple",), 2),
):
    for _word in _words:
        _WORD_UNITS[_word] = _units

#: **كلماتُ الربط فاصلٌ لا كلمة** — «سبعة و تسعين» و«079 ثمّ 123» تتابعٌ واحد. **وكلُّ كلمةٍ منها فاصلٌ واحدٌ أيّاً كان طولُها**:
#: «then» أربعةُ أحرف، وعدُّها بحروفها كان يجعلها قاطعاً
_CONNECTORS = frozenset({"و", "ثم", "بعدين", "and", "then"})

#: **الامتداداتُ التي تُقرأ رابطاً** — مصرَّحةٌ لا «أيُّ حروفٍ بعد نقطة»
_TLDS = (
    "com", "net", "org", "info", "biz", "io", "me", "co", "app", "link", "xyz", "site", "online", "store", "shop", "live",
    "club", "top", "dev", "page", "ai", "gg", "tv", "cc", "ws", "to", "ly", "jo", "sa", "ae", "eg", "iq", "ps", "lb",
    "sy", "uk", "us", "ru", "tk", "ml", "ga", "cf", "gq", "edu", "gov",
)
_LINK = re.compile(
    r"(?:https?://|www\.|\b[\w-]{1,63}(?:\.[\w-]{1,63})*\.(?:" + "|".join(_TLDS) + r")\b)",
    re.IGNORECASE,
)


def _strip_invisible(text: str) -> str:
    """`NFKC` ثمّ نزعُ ما لا يُرى: علاماتُ التشكيل (`Mn`) وما يركب الحرف (`Me`) وأحرفُ التنسيق (`Cf`: الصفريّةُ العرض والاتجاه) والتطويل."""
    normalized = unicodedata.normalize("NFKC", text)
    return "".join(
        ch
        for ch in normalized
        if ch != _TATWEEL and unicodedata.category(ch) not in {"Mn", "Me", "Cf"}
    )


def _latin(ch: str) -> str:
    """**كلُّ خانةٍ عشريّةٍ في أيِّ كتابةٍ** ← لاتينية — العربيةُ الهندية والفارسية وغيرهما بقاعدةٍ واحدة لا بجدول."""
    if ch.isdigit() and unicodedata.category(ch) == "Nd":
        return str(unicodedata.decimal(ch))
    return ch


def _fold(word: str) -> str:
    """كلمةٌ كما تُقارن: صغيرةُ الأحرف، **والألفاتُ ألفٌ والتاءُ المربوطةُ هاءٌ والألفُ المقصورةُ ياء** — فـ«إثنين» و«اثنين» واحدة."""
    word = word.lower()
    return word.translate(str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ة": "ه", "ى": "ي"}))


def _word_units(word: str) -> int | None:
    """وحداتُ كلمةِ العدد — **و«و» العطف الملتصقة تُنزع** («وخمسين»). و`None` لكلمةٍ ليست عدداً."""
    folded = _fold(word)
    if folded in _WORD_UNITS:
        return _WORD_UNITS[folded]
    if folded.startswith("و") and folded[1:] in _WORD_UNITS:
        return _WORD_UNITS[folded[1:]]
    return None


def _normalize(text: str) -> str:
    """النصُّ كما يُعدّ: بلا ما لا يُرى، وبخاناتٍ لاتينية."""
    return "".join(_latin(ch) for ch in _strip_invisible(text))


def _allowed_pattern(value: str) -> re.Pattern[str] | None:
    """**نمطُ قيمةٍ مسموحةٍ بعينها** (لوحةُ مركبة الرحلة) — حروفُها وخاناتُها بترتيبها، **وبينها أيُّ فاصلٍ أو لا شيء**: «13-12345»
    و«13 12345» و«1312345» و«١٣-١٢٣٤٥» واحدة.

    **ولا تُقتطع من وسط رقمٍ أطول** (`(?<![0-9])`/`(?![0-9])`): «0791312345» لا يصير «079» لأن فيه خاناتِ اللوحة.
    """
    chars = [ch for ch in _normalize(value) if ch.isalnum()]
    if not any(ch.isdigit() for ch in chars):
        return None
    body = r"[\W_]*".join(re.escape(ch) for ch in chars)
    return re.compile(r"(?<![0-9])" + body + r"(?![0-9])", re.IGNORECASE)


def _without_allowed(cleaned: str, allowed: Iterable[str]) -> str:
    """**تُرفع القيمُ المسموحةُ بفراغ** — والفراغُ لا يقطع العدّ: رقمٌ يُدسّ حول اللوحة («0791 13-12345 234567») يلتئم حولها فيُردّ."""
    for value in allowed:
        pattern = _allowed_pattern(value)
        if pattern is not None:
            cleaned = pattern.sub(" ", cleaned)
    return cleaned


def _run_of(cleaned: str) -> int:
    best = units = gap = 0
    i, n = 0, len(cleaned)
    while i < n:
        ch = cleaned[i]
        if ch.isdigit():
            units += 1
            gap = 0
            i += 1
        elif ch.isalpha():
            j = i
            while j < n and cleaned[j].isalpha():
                j += 1
            word = cleaned[i:j]
            value = _word_units(word)
            if value is not None:
                units += value
                gap = 0
            elif _fold(word) in _CONNECTORS and units:
                gap += 1
                if gap > MAX_SEPARATOR_RUN:
                    units = gap = 0
            else:
                units = gap = 0
            i = j
        elif ch.isspace():
            # **الفراغُ لا يُعدّ ولا يقطع** — أسطرٌ جديدةٌ بين أجزاء الرقم لا تخفيه
            i += 1
        elif ch in _BREAKERS:
            units = gap = 0
            i += 1
        else:
            # **كلُّ ما ليس حرفاً ولا خانةً ولا فراغاً فاصل** — لا قائمةٌ تُنسى منها «·» أو «🙂»
            if units:
                gap += 1
                if gap > MAX_SEPARATOR_RUN:
                    units = gap = 0
            i += 1
        best = max(best, units)
    return best


def longest_number_run(text: str, *, allowed: Iterable[str] = ()) -> int:
    """**أطولُ تتابعٍ لوحدات الرقم** في النصّ — خاناتٌ وكلماتُ عددٍ بينها فواصلُ قصيرة. انظر رأسَ الملف."""
    return _run_of(_without_allowed(_normalize(text), allowed))


def has_link(text: str) -> bool:
    return _LINK.search(_strip_invisible(text)) is not None


def check(text: str, *, allowed: Iterable[str] = ()) -> Violation | None:
    """**الحكمُ الواحد**: رقمٌ أولاً ثمّ رابط — أو `None` إن مرّ النصّ.

    **و`allowed` قيمٌ بعينها يعرفها الطرفان سلفاً** — لوحةُ مركبة هذه الرحلة («13-12345» سبعُ خانات، ويراها الراكبُ في بطاقة
    كبتنه). **تُرفع هي وحدَها قبل العدّ، ولا يُستثنى شكلُ اللوحة عامّةً**: استثناءُ «خانتان-خمس» يجعل كلَّ رقمٍ يُكتب بشكل لوحةٍ
    يمرّ — وهو بابٌ لا استثناء.
    """
    if longest_number_run(text, allowed=allowed) >= MIN_PHONE_UNITS:
        return Violation.PHONE
    if has_link(text):
        return Violation.LINK
    return None
