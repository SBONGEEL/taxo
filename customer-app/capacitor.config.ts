/** تغليفُ تطبيق الراكب في APK — **غلافٌ أصليٌّ حول الخادم الحيّ** (قرارُ المالك).
 *
 * `server.url` يعني أن الشاشاتِ تُحمَّل من النطاق لا من داخل الحزمة. وثمنُه
 * مكتوبٌ صراحةً: **التطبيقُ لا يعمل والنطاقُ مغلق**. ومقابلُه أن كلَّ ما
 * تحقّقنا منه يبقى عاملاً بلا إعادة ضبط — قيودُ URL لتوكن Mapbox، ونطاقاتُ
 * Firebase المصرَّح بها، والمقبسُ — لأن **المصدرَ هو النطاقُ نفسُه** الذي
 * فُتح في المتصفح، لا `capacitor://localhost` الذي لا يعرفه أحدٌ من هؤلاء.
 *
 * **و`androidScheme: "https"` مقصود**: بلا ذلك يكون المصدرُ `http://localhost`
 * فتصير كلُّ نداءاتنا محتوىً مختلطاً معكوساً — والأسوأُ أن `localStorage`
 * يُعزَل عن أصلٍ آخر، فتضيع الجلسةُ بين تشغيلين.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * **والقيمُ من `channels.json` لا من هنا** (أربعُ نسخ، 2026-08-26): المعرّفُ
 * والاسمُ وعنوانُ الغلاف تُشتقّ من `TAXO_CHANNEL`. **ولا افتراضَ للقناة** —
 * غيابُها يوقف البناء، لأن **بناءً ينجح بقناةٍ لم يقصدها أحدٌ يُشحن**، وبناءً
 * يسقط يُقرأ.
 *
 * **والمعرّفُ هنا يجب أن يطابق `applicationId` الذي تنتجه نكهةُ gradle** —
 * وإلا صار داخلُ الحزمة يقول شيئاً وبيانُها يقول آخر. **وحارسُ `check:apk`
 * يقيس الزوجَ من داخل الحزمة** فلا يبقى التطابقُ دعوى.
 * ═══════════════════════════════════════════════════════════════════════════
 */

import type { CapacitorConfig } from "@capacitor/cli";
import { fromEnv } from "../tools/channels.mjs";

const ch = fromEnv("customer-app");

const config: CapacitorConfig = {
  appId: ch.appId,
  appName: ch.appName,
  // مطلوبٌ حتى مع `server.url`: الأداةُ تتحقق من وجوده وإن لم تنسخ منه شيئاً
  webDir: "dist",
  android: {
    allowMixedContent: false,
  },
  server: {
    url: ch.shellUrl,
    androidScheme: "https",
    // **لا `cleartext`**: كلُّ شيءٍ خلف HTTPS، وفتحُ النصِّ الصريح هنا يجعل
    // أوّلَ خطأ عنوانٍ يمرّ بلا أن يُرى بدل أن يُرفض
    cleartext: false,
  },
  // **لا إضافةَ شاشةِ بدء** (قرارُ المالك 2026-08-14): كانت ترسم الشعارَ ثم
  // ترسمه الشاشةُ الترحيبيةُ المتحركة مرةً ثانية.
};

export default config;
