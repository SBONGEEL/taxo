/** إزالةُ الشاشة الترحيبية — `DESIGN.md` §7.5.
 *
 * **فورَ جاهزية التطبيق لا بعد انتهاء الحركة**: الحركةُ تملأ انتظاراً ولا
 * تصنعه، فإن كان التطبيق أسرع منها قُطعت في منتصفها. وهذا هو الفرقُ بين شاشةٍ
 * ترحيبيةٍ وشاشةِ تأخير.
 *
 * والعقدةُ تعيش في `index.html` لا في React (لتُرسم قبل الحزمة)، فإزالتُها
 * لمسٌ مباشرٌ للـDOM — وهو الاستثناءُ الوحيد في هذا التطبيق، ومحصورٌ هنا.
 *
 * **وتُستدعى مرةً ولو نُوديت مراراً**: `Boot` يُعاد رسمُه، و`StrictMode` يُشغّل
 * التأثيرات مرتين في التطوير — فحذفٌ بلا حارسٍ يرمي خطأً في الثانية.
 */

const FADE_MS = 200;

let done = false;

export function hideSplash(): void {
  if (done) return;
  done = true;

  const node = document.getElementById("splash");
  if (!node) return;

  node.classList.add("is-gone");
  // تُحذف بعد الذوبان لا تُخفى: عقدةٌ `fixed` باقيةٌ فوق كل شيء تبتلع اللمس
  window.setTimeout(() => node.remove(), FADE_MS);
}
