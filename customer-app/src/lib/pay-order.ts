/** **ترتيبُ طرق الدفع كما ضبطه المالكُ لسوقه** (أمرُ المالك ٢٠٢٦-١١-١٣: «Whop first for Jordan») — من `/config`.
 *
 * **عرضٌ لا إذن**: «البطاقةُ أوّلاً» تعني أنّ زرَّها يُرسم أوّلاً ومقترحاً مسبقاً، والطرقُ الأخرى تحته كما هي ويختارها الشخصُ متى
 * شاء — **لا تُجبر أحداً على بطاقة**. ولا يُظهر الترتيبُ طريقةً: كلُّ طريقةٍ يحكمها مفتاحُها وعقدُها. **وقائمةٌ فارغةٌ «كما كان»**
 * (الجزائرُ وليبيا): لا يتغيّر فيهما حرف. */

import type { PaymentOrderKey } from "@/api/types";

export function cardFirst(order: readonly PaymentOrderKey[] | null | undefined): boolean {
  return (order ?? [])[0] === "card";
}
