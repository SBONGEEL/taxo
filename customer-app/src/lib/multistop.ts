/** «هل تعدد الوجهات معروضٌ على صاحب هذه الشاشة؟» — سؤالٌ بجواب واحد.
 *
 * يجيبه هذا الملف وحده فتتفق عليه الشاشات: زرُّ «إضافة محطة» في شاشة الطلب،
 * وقائمةُ المحطات، وسطرُ رسم الانتظار. ولو أجابت كلُّ شاشةٍ بنفسها لظهر الزرُّ
 * في واحدةٍ وغاب عن أخرى بعد أول تعديل — وهو ما وقع فعلاً مع الخدمة النسائية
 * قبل أن يُكتب `lib/women.ts`.
 *
 * **ومطفأً لا يظهر شيءٌ إطلاقاً**: لا زرٌّ معطّل ولا رسالةُ اعتذار — نفس قاعدة
 * `women_service_enabled` (SPEC القسم 4/`feature_flags`). زرٌّ معطّل يعرض على
 * الراكب ما لا يناله، ورسالةٌ تعتذر تعِد بما لم يُوعَد به.
 *
 * **والإخفاءُ راحةٌ لا حماية**: الخلفيةُ ترفض محطاتٍ في دولةٍ مفتاحُها مطفأ
 * (`multi_stop_unavailable`) عند **إنشاء الطلب** لا عند عرضه — فطلبٌ مصنوعٌ
 * بيد يرتدّ.
 */

import { useFeature } from "@/lib/config";
import { useSession } from "@/lib/session";

/** حتى **ثلاث وجهات** في الرحلة: وسيطتان والأخيرة. مرآةُ
 * `models/ride.py::MAX_INTERMEDIATE_STOPS` — والخلفيةُ ترفض ما زاد. */
export const MAX_STOPS = 2;

export function useMultiStop(): boolean {
  const { user } = useSession();
  return useFeature(user?.country_code, "multi_stop_enabled");
}
