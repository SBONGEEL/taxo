/** مركبةُ الكبتن على شاشة الراكب — **بيتٌ واحدٌ لعنوانها وحجمها**.
 *
 * موضعان يرسمانها (الخريطةُ وبطاقةُ «الكبتن في الطريق»)، **وبيتان يحسبان
 * عنوانَها يفترقان أوّلَ تعديلٍ في الخلفية** — وهو الشكلُ الثامن قبل أن
 * يُكتب سطرٌ ثانٍ.
 */

import { API_URL } from "@/api/client";
import type { RideDriverSkin } from "@/api/types";

/** **حجمُ العلامة على الخريطة — ثابتٌ في الكود** ثم يُضرب في نسبة المشرف.
 *
 * **و٣٠ هي مقاسُ السيارة العامّة نفسُه** (`MapView.carElement`، مقيسٌ على عرض
 * ٣٩٠ بكسل = ٧٫٧٪ من العرض): فالمركبةُ تحلّ محلَّها بنفس الثقل البصريّ،
 * **ولا يُقرأ اختلافُ الحجم فرقاً بين كبتنٍ وكبتن**.
 *
 * **ولا يُقرأ الحجمُ من المستطيل المحيط**: مربّعٌ بزاوية ١٢٤٫٩° محيطُه
 * ٣٠×١٫٣٩ ≈ ٤٢ — **حجمُ الالتفاف لا حجمُ الأيقونة** (`CLAUDE.md`).
 */
export const SKIN_BASE_PX = 30;

/** الحجمُ المعروض بالبكسل — **نسبةُ المشرف ٨٠–١٢٠٪ محروسةٌ في الخلفية**،
 *  وتُقصّ هنا أيضاً لأن قيمةً شاذّةً تصل يوماً ترسم مركبةً تغطّي الخريطة. */
export function skinSizePx(skin: RideDriverSkin): number {
  const percent = Math.min(200, Math.max(50, skin.scale_percent || 100));
  return Math.round((SKIN_BASE_PX * percent) / 100);
}

/** عنوانُ رسمةٍ نسبيٍّ مبنيٌّ على أصل الخادم.
 *
 * **و`new URL` لا وصلُ نصّين**: مسارٌ يبدأ بـ`/` يُقاس من جذر المضيف، ومسارٌ
 * بلا `/` يُقاس من موضع الـAPI، **وعنوانٌ مطلقٌ يمرّ كما هو** — والثلاثةُ
 * صحيحةٌ بلا شرطٍ نكتبه ونخطئ فيه. **والعقدُ يقول «نسبيّان يبنيهما التطبيقُ
 * على أصله»** (`schemas/vehicle_skin.py`)، فهذا هو البناء.
 */
export function skinImageUrl(path: string): string {
  try {
    return new URL(path, API_URL).toString();
  } catch {
    // عنوانٌ لا يُفهم — يُعاد كما هو، وفشلُ الصورة يُسقطها إلى السيارة العامّة
    return path;
  }
}
