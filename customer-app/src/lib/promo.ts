/** «هل الكوبوناتُ معروضةٌ على صاحب هذه الشاشة؟» — سؤالٌ بجواب واحد.
 *
 * يجيبه هذا الملف وحده كما يفعل `lib/multistop.ts` و`lib/women.ts`: ورقةُ
 * الكوبون في تأكيد الطلب هي القارئُ الوحيد اليوم، وصفُّ الإيصال يقرأ الدفعةَ
 * لا المفتاح — فما وقع يُعرض ولو أُطفئ المفتاحُ بعده.
 *
 * **ومطفأً لا يظهر شيءٌ إطلاقاً**: لا زرَّ «عندي كوبون» ولا حقلاً معطّلاً. وزرٌّ
 * يفتح حقلاً لا يُقبل فيه رمزٌ أسوأ من غيابه — يجعل الراكبَ يجرّب رموزاً ثم
 * يظن العرضَ كاذباً.
 *
 * **والإخفاءُ راحةٌ لا حماية**: الخلفيةُ ترفض رمزاً في دولةٍ مفتاحُها مطفأ
 * (`promo_unavailable`) في التحقق وفي إنشاء الطلب معاً (SPEC القسم 6.6).
 */

import { useFeature } from "@/lib/config";
import { useSession } from "@/lib/session";

export function usePromoCodes(): boolean {
  const { user } = useSession();
  return useFeature(user?.country_code, "promo_codes_enabled");
}
