/** ارتفاعُ ما يُرى فعلاً — **لا ما يقوله `dvh`**.
 *
 * **العطبُ مقيسٌ على S21 بلوحة مفاتيحَ حقيقية** (2026-08-23): حين تُفتح
 * لوحةُ المفاتيح في WebView أندرويد **لا يتقلّص إطارُ التخطيط**:
 *
 * | المقياس | القيمة |
 * |---|---|
 * | `innerHeight` | ٨٠٠ |
 * | `100dvh` · `100vh` · `100svh` | **٨٠٠ — كلُّها** |
 * | `visualViewport.height` | **٤٥٨** |
 *
 * فالورقةُ المسقوفةُ بـ`calc(100dvh - N)` تمتدّ تحت لوحة المفاتيح: قِيس
 * **٣٤٢ بكسلاً خلفها** في ورقة التحويل — **والمبلغُ و«رصيدك بعده» و«أرسل
 * الآن» ثلاثتُها غيرُ مرئية**؛ و**٢٥٠** في قدم الأجرة حين يُفتح حقلُ
 * الكوبون، **فالسعرُ والزرُّ معاً خلفها**.
 *
 * **ولا وحدةَ CSS تتبع `visualViewport`** — فالمخرجُ الوحيد أن نقيسه ونكتبه
 * متغيّراً تقرؤه الأوراق.
 *
 * **ولمَ لم يُكشف قبل اليوم**: القياسُ السابق كان **محاكاةَ إطار**
 * (`Emulation.setDeviceMetricsOverride`)، **وهي تُقلّص `innerHeight`** فيتبعه
 * `dvh` فيتقلّص السقفُ ويبدو العلاجُ ناجحاً. **ولوحةُ المفاتيح الحقيقيةُ لا
 * تفعل ذلك** — وهو الشكلُ الحادي عشر: عائقٌ لا يُرى إلا على جهاز.
 *
 * **ويُركَّب مرةً في الجذر**: مستمعان على `visualViewport` وحدَه — لا على
 * `resize` العامّ — فلا يعمل شيءٌ في متصفّحٍ لا يدعمه، ويبقى `dvh` احتياطَه
 * عبر `fallback` في CSS.
 */

/** اسما المتغيّرين — **يُقرآن من CSS وحدَهما**، ولا يُكتب رقمُهما في مكوّن. */
const HEIGHT = "--vvh";
/** **ما تحجبه لوحةُ المفاتيح من أسفل الإطار** — والسقفُ وحدَه لا يكفي:
 *  الورقةُ مثبَّتةٌ من **أسفل إطار التخطيط** (٨٠٠)، فحافّتُها السفلى تبقى
 *  تحت المرئيِّ (٤٥٨) مهما قصُر ارتفاعُها. **فتُرفع بمقدار المحجوب.** */
const INSET = "--vv-bottom";

/** يكتب ارتفاعَ المرئيِّ في الجذر. **ويُستدعى عند التغيير والانزلاق معاً**:
 *  لوحةُ المفاتيح تغيّر الارتفاع، والانزلاقُ يغيّر `offsetTop` — وورقةٌ
 *  مثبَّتةٌ من الأسفل تتبع الاثنين. */
function write(): void {
  const view = window.visualViewport;
  if (!view) return;
  const root = document.documentElement;
  root.style.setProperty(HEIGHT, `${Math.round(view.height)}px`);
  // **المحجوبُ = الإطارُ ناقصَ (المرئيُّ + إزاحتُه)** — وهو صفرٌ بلا لوحةِ
  // مفاتيح، فلا أثرَ لهذا السطر في الحال العادية
  const hidden = Math.max(
    0,
    Math.round(window.innerHeight - view.height - view.offsetTop),
  );
  root.style.setProperty(INSET, `${hidden}px`);
}

/** يُركَّب مرةً واحدةً عند الإقلاع — ويعيد دالّةَ الفكّ. */
export function trackVisualViewport(): () => void {
  const view = window.visualViewport;
  // **متصفّحٌ بلا دعم يبقى على `dvh`**: لا نكتب المتغيّرَ أصلاً، فتأخذ CSS
  // قيمتَها الاحتياطية. وكتابةُ `innerHeight` هنا **تكذب بنفس قدر `dvh`**
  // وتُخفي أن القياسَ غيرُ متاح.
  if (!view) return () => {};
  write();
  view.addEventListener("resize", write);
  view.addEventListener("scroll", write);
  return () => {
    view.removeEventListener("resize", write);
    view.removeEventListener("scroll", write);
  };
}
