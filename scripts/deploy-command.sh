#!/usr/bin/env bash
# **الأمرُ الوحيدُ الذي يفتحه مفتاحُ النشر** — يُفرض في `authorized_keys`:
#
#   command="/home/taxo/taxo/scripts/deploy-command.sh",no-pty,\
#   no-port-forwarding,no-agent-forwarding,no-X11-forwarding,no-user-rc ssh-ed25519 AAAA…
#
# **ولمَ أمرٌ مفروضٌ لا مفتاحٌ بعبارةِ مرور** (قرارُ المالك 2026-08-21): وكيلٌ
# حيٌّ يعطي **كلَّ برنامجٍ محليٍّ صدفةً كاملةً** على الخادم، وهذا يعطي **أمراً
# واحداً**. **فالحدُّ في الخادم لا في السرّية** — ويبقى صحيحاً بعد أن يُسرق
# الملف.
#
# **وما يستطيعه حاملُه، جملةً واحدة:**
#
#   يستطيع أن يجعل صفحةَ التنزيل تخدم حزمَ **إصدارٍ منشورٍ على GitHub**
#   باسمه، ولا شيءَ غيرَ ذلك — لا صدفةَ، ولا قراءةَ ملفّ، ولا قاعدةَ بيانات،
#   ولا `.env`، **ولا حتى وسمٌ لا وجودَ له**.
#
# **والرفضُ هو المقيس**: `scripts/tests/deploy-command.test.sh` يطرقه بأوامرَ
# أخرى ويشترط الردَّ — **لأن نجاحَ السحب لا يقول شيئاً عمّا يُرفض**.
set -euo pipefail

deny() {
  printf 'مرفوض: هذا المفتاحُ لا يفتح إلا سحبَ إصدارٍ بوسمه.\n  %s\n' "$1" >&2
  exit 42
}

REQUEST="${SSH_ORIGINAL_COMMAND:-}"
[ -n "$REQUEST" ] || deny "لا أمرَ — والصدفةُ التفاعلية ممنوعةٌ على هذا المفتاح."

# **يُقرأ الوسمُ ولا يُنفَّذ النصّ**: لا `eval` ولا تمريرٌ إلى صدفة — فالسطرُ
# الوارد **بياناتٌ لا أمر**. وهي القاعدةُ التي تمنع «؛» و«&&» أن تصير باباً.
read -r verb tag extra <<<"$REQUEST"

[ "$verb" = "pull-release" ] || deny "الفعلُ المسموح `pull-release` وحدَه — ووصل: ${verb:-<فارغ>}"
[ -z "${extra:-}" ] || deny "وسيطٌ زائد — الأمرُ كلمتان لا أكثر."
[ -n "${tag:-}" ] || deny "لا وسمَ في الطلب."

# **والوسمُ شكلُه محروس**: `v` ورقمٌ ونقاط — فلا مسارَ ولا `..` ولا مسافة،
# ولا شيءَ يصلح أن يكون خياراً لـ`curl` أو جزءاً من مسار.
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || deny "وسمٌ غيرُ مقبولٍ الشكل: $tag"

: "${TAXO_GITHUB_REPO:=SBONGEEL/taxo}"

# **الرمزُ من ملفٍّ لا من البيئة** — و`sshd` لا يمرّر بيئةً إلى أمرٍ مفروض،
# فاشتراطُ متغيّرٍ هنا شرطٌ لا يتحقّق أبداً. **وملفُّه ٦٠٠ ولمالكه وحدَه**،
# ولا يُطبع ولا يدخل git.
TOKEN_FILE="${TAXO_RELEASE_TOKEN_FILE:-$HOME/.taxo/release-token}"
if [ -z "${TAXO_RELEASE_TOKEN:-}" ] && [ -r "$TOKEN_FILE" ]; then
  TAXO_RELEASE_TOKEN="$(tr -d '
' < "$TOKEN_FILE")"
fi
[ -n "${TAXO_RELEASE_TOKEN:-}" ] || deny "لا رمزَ قراءةٍ على الخادم ($TOKEN_FILE)."

cd "$(dirname "$0")/.."
exec bash scripts/pull-release.sh "$tag" "$TAXO_GITHUB_REPO" "$TAXO_RELEASE_TOKEN"
