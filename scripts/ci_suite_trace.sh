#!/usr/bin/env bash
# **النتيجةُ كاملةً عند السقوط** — كانت منسوخةً في وظيفتين، فصارت هنا مرّةً (2026-11-15).
#
# **الأثرُ يصل كاملاً** — و`tail` وحدَه لا يكفي: بألفِ خطأٍ تكون آخرُ ١٢٠ سطراً قائمةَ الأسماء لا الأثر (التشغيل ٤٣).
# **والرأسُ موضعُ الأثر**. **والعنوانُ يُقنَّع** بشكليه — `://مستخدم:كلمة@` و`ConnectionParameters(password='…')` من تتبّع
# asyncpg، **وهذا الثاني هو الذي يتسرّب فعلاً** (١٦ مرّةً في مخرَجِ كلمةٍ خاطئة، قِيس 2026-08-24).
OUT=backend/.suite.out
if [ ! -f "$OUT" ]; then
  echo "لا ملفَّ نتيجةٍ — سقط قبل أن تبدأ المجموعة."
  exit 0
fi
mask() {
  sed -E -e 's#(://[^:/@]+):[^@]*@#\1:***@#g' \
         -e "s#(password=)('[^']*'|\"[^\"]*\"|[^,)[:space:]]+)#\\1'***'#g" \
         "$OUT"
}
echo "════════ أوّلُ ١٢٠ سطراً — وفيها الأثر ════════"
mask | head -120
echo
echo "════════ آخرُ ٦٠ سطراً — الحصيلة ════════"
mask | tail -60
echo
echo "════════ الأسبابُ المتمايزة وعددُ كلٍّ ════════"
grep -oE '[A-Za-z_.]+(Error|Exception)' "$OUT" | sort | uniq -c | sort -rn | head -15
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
  grep -E '^(FAILED|ERROR)' "$OUT" | head -40 >> "$GITHUB_STEP_SUMMARY" || true
fi
