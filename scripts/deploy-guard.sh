# shellcheck shell=bash
# **لا موتَ صامتاً للمشغّل** — يُستورد من `scripts/deploy.sh` بعد `set -euo pipefail` (أُضيف ٢٠٢٦-١١-١٧).
#
# **العلّةُ مقيسة** (رفعُ ٢٠٢٦-١١-١٦ `be8efd15`): مات المشغّلُ بعد «✓ الصحّةُ عبر النفق» **بلا سطرٍ واحد**،
# فأُكملت البوّابةُ ٦ يدويّاً. والسببُ شكلُ السطر لا الشبكة:
#
#     _len="$(curl … "$EDGE/$_p" | wc -c | tr -d ' ')"
#
# **إسنادٌ من تعويضِ أمرٍ يأخذ رمزَ خروج الأنبوب**، ومع `pipefail` يصير رمزُ `curl` الساقط (تقطّعُ شبكة الجهاز)
# — أو رمزُ `grep` الذي لم يجد — رمزَ الإسناد، **فيقتل `errexit` المشغّلَ قبل أن يبلغ `die`** الذي كُتب ليقول ما سقط.
# فالحارسُ موجودٌ ومكتوبٌ بنصّه، **ولا يُنادى أبداً** — وهو «شرطٌ لا يتحقّق يُقرأ حراسة» بعينه.
#
# **والعلاجُ طبقتان، وكلٌّ تُقاس** (`scripts/tests/deploy-silent-exit.test.sh`):
#  ١) `edge_get`: جلبٌ يعيد ثلاثاً **ولا يُسقط المشغّل** — فراغُه يصل إلى `die` الذي يسمّي ما لم يُقس.
#  ٢) فخُّ `ERR`/`EXIT`: **أيُّ** خروجٍ غيرِ صفريٍّ لم يمرّ بـ`die` يُطبع بسطره وأمره ورمزه — فلا يكون الموتُ التالي صامتاً
#     ولو جاء من سطرٍ لم يُكتب بعد.

_DEPLOY_DIED=""
_DEPLOY_ERR_LINE=""
_DEPLOY_ERR_CMD=""

# **`-E`**: بدونه لا يرث فخُّ `ERR` الدوالَّ ولا الأصدافَ الفرعيّة، فيضيع سطرُ الموت داخلها.
set -E
# **الأخيرُ لا الأوّل**: فشلٌ سابقٌ احتُمل في صدفةٍ فرعيّة لا يُنسب إليه الموتُ اللاحق
trap '_DEPLOY_ERR_LINE=$LINENO; _DEPLOY_ERR_CMD=$BASH_COMMAND' ERR

_deploy_on_exit() {
  local rc=$?
  if [ "$rc" -ne 0 ] && [ -z "$_DEPLOY_DIED" ]; then
    printf '\n✗ **المشغّلُ خرج بلا رسالة** (رمز %s) عند السطر %s: %s\n' \
      "$rc" "${_DEPLOY_ERR_LINE:-?}" "${_DEPLOY_ERR_CMD:-<غيرُ معروف>}" >&2
    printf '  لا يُقرأ هذا خُضرةً ولا يُكمَل يدويّاً قبل قراءة السطر. والنسخةُ إن أُخذت في %s\n' "${LOCAL:-<لم تُؤخذ بعد>}" >&2
  fi
}
trap _deploy_on_exit EXIT

# `die` يعلّم أنه قال ما سقط — فلا يتكرّر السطرُ بصيغتين
deploy_died() { _DEPLOY_DIED=1; }

# جلبٌ من الحافّة: ثلاثُ محاولاتٍ بفاصل ثانيتين، **ولا رمزَ خروجٍ غيرَ صفريٍّ أبداً** — الفراغُ هو الجواب حين لا يصل شيء.
edge_get() {
  local url="$1" out="" i
  for i in 1 2 3; do
    out="$(curl -sS --max-time "${EDGE_TIMEOUT:-15}" "$url" 2>/dev/null)" && [ -n "$out" ] && break
    out=""
    [ "$i" -lt 3 ] && sleep "${EDGE_RETRY_SLEEP:-2}"
  done
  printf '%s' "$out"
  return 0
}
