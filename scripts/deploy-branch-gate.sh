#!/usr/bin/env bash
# **لا رفعَ إلا من `master`** — البوّابةُ صفر، قبل الإعلان وقبل أيِّ نداءٍ
# للخادم (قرارُ المالك ٢٠٢٦-١٠-٠٤).
#
# **علّتُها شجرةُ عملٍ ثانية**: `~/prj/TAXO-redesign` على الفرع `redesign`
# لإعادة التصميم — **لا تُرفع أبداً، ودمجُها في `master` بقول المالك وحدَه**.
# و`deploy.sh` يرفع **HEAD الدليلِ الذي يُشغَّل منه** (`git push origin HEAD`
# ثمّ يسحب الخادمُ الإيداعَ نفسَه منفصلاً) — **فلو شُغِّل من هناك لَرُفع فرعٌ
# لم يُدمج**، ولا بوّابةَ من الخمس تسأل عن الفرع.
#
# **ويُسأل كلُّ دليلٍ يُمرَّر، و`deploy.sh` يمرّر اثنين**: الدليلَ الحاليّ
# (ما سيُرفع) **ومستودعَ السكربت نفسِه** — فمن نادى سكربتَ `master` وهو داخل
# شجرة التصميم رفع شجرةَ التصميم بسكربتٍ سليم، ومن نادى سكربتَ التصميم من
# `master` رفع بسكربتٍ لم يُدمج.
#
# **وثلاثةُ أسبابٍ للرفض، ويُسمّى كلٌّ باسمه** — فخطأٌ يسمّي غيرَ سببه شكلٌ
# مسجَّلٌ في `PATTERNS.md`: فرعٌ غيرُ `master` · رأسٌ منفصلٌ لا فرعَ له ·
# **وgit لم يقرأ المستودعَ أصلاً** (فيُطبع نصُّه كما هو).
#
# **وحدُّه مكتوبٌ لا مسكوتٌ عنه**: يسأل **أيَّ فرعٍ يُرفع**، لا **ما الذي
# دخل `master`** — فدمجُ `redesign` في `master` بغير قول المالك لا يمسكه هذا،
# ويبقى شرطاً بشرياً مكتوباً في `CLAUDE.md`.
#
#     bash scripts/deploy-branch-gate.sh <دليل>...      # يخرج ٠ أو ١
#
# ومقيسٌ في الاتجاهين: `scripts/tests/deploy-branch-gate.test.sh`.
set -uo pipefail

refuse() {
  printf '\n✗ لا رفعَ إلا من master — %s\n' "$1" >&2
  [ -n "${2:-}" ] && printf '  %s\n' "$2" >&2
  printf '  والرفعُ لم يبدأ: لا بوّابةَ فُتحت ولا نداءَ للخادم.\n' >&2
  printf '  وشجرةُ إعادة التصميم (redesign) لا تُرفع أبداً، ودمجُها بقول المالك وحدَه.\n\n' >&2
  exit 1
}

# **وغيابُ ما يُقاس لا يُقرأ سلامة**: نداءٌ بلا دليلٍ يُرفض لا يمرّ.
[ "$#" -ge 1 ] || refuse "لا دليلَ يُسأل عن فرعه." "وغيابُ ما يُقاس لا يُقرأ سلامة."

for dir in "$@"; do
  branch="$(git -C "$dir" symbolic-ref --quiet --short HEAD 2>/dev/null)"
  rc=$?
  case "$rc" in
    0)
      [ "$branch" = "master" ] \
        || refuse "$dir على الفرع «$branch»." "وما يُرفع هو HEAD هذا الدليل."
      ;;
    1)
      refuse "$dir على رأسٍ منفصل — لا فرعَ له." "فلا يُقال إنه master."
      ;;
    *)
      refuse "git لم يقرأ $dir." "$(git -C "$dir" rev-parse --git-dir 2>&1 | head -2)"
      ;;
  esac
done
exit 0
